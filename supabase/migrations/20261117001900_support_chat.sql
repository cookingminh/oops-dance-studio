-- The message text: trimmed, up to 2000 characters; null when empty.
create function private.support_body(p_body text)
returns text
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_body text := nullif(btrim(p_body), '');
begin
  if char_length(v_body) > 2000 then
    raise exception 'INVALID_INPUT: a message is up to 2000 characters';
  end if;
  return v_body;
end;
$$;

-- A photo for someone's conversation: in that person's folder and already uploaded.
create function private.support_image(p_customer uuid, p_path text)
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if p_path is null then
    return null;
  end if;
  if p_path !~ ('^' || p_customer::text || '/[A-Za-z0-9_-]{1,100}\.(jpg|jpeg|png|webp)$') then
    raise exception 'INVALID_INPUT: the chat photo must be %/<name>.{jpg|jpeg|png|webp}', p_customer;
  end if;
  if not exists (select 1 from storage.objects o where o.bucket_id = 'support-images' and o.name = p_path) then
    raise exception 'INVALID_INPUT: chat photo % has not been uploaded', p_path;
  end if;
  return p_path;
end;
$$;

-- Students, guests and instructors: up to 20 messages in 10 minutes.
create function private.support_rate_check(p_uid uuid)
returns void
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if (select count(*) from public.support_messages m
       where m.sender_id = p_uid and m.created_at > now() - interval '10 minutes') >= 20 then
    raise exception 'RATE_LIMITED: too many messages; wait a few minutes';
  end if;
end;
$$;

-- What the person hasn't read yet: the studio's replies and its questions to them (not the night notes).
create function private.support_unread_for_customer(p_thread bigint, p_since timestamptz)
returns integer
language sql
stable
security definer
set search_path = ''
as $$
  select count(*)::integer from public.support_messages m
   where m.thread_id = p_thread and m.created_at > p_since
     and (m.sender_kind in ('staff', 'ai') or m.event in ('close_asked', 'auto_closed'));
$$;

-- What staff haven't read yet: the person's messages.
create function private.support_unread_for_staff(p_thread bigint, p_since timestamptz)
returns integer
language sql
stable
security definer
set search_path = ''
as $$
  select count(*)::integer from public.support_messages m
   where m.thread_id = p_thread and m.sender_kind = 'customer' and (p_since is null or m.created_at > p_since);
$$;

