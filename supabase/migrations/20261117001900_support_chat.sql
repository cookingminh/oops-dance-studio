-- Ask a question: a new conversation with its first message. Only during 'open' hours, one open at a time.
create function public.support_start(p_category text, p_body text, p_image_path text default null, p_opened_from text default null)
returns public.support_threads
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_role public.app_role := public.current_app_role();
  v_body text := private.support_body(p_body);
  t public.support_threads;
begin
  if v_uid is null or v_role is null or v_role not in ('guest', 'instructor') then
    raise exception 'FORBIDDEN: students, guests and instructors start a conversation; staff answer from the Inbox';
  end if;
  if private.support_phase(now()) <> 'open' then
    raise exception 'SUPPORT_CLOSED: %', private.support_hours_text('start');
  end if;
  if p_category is null or not (p_category = any (private.support_categories(v_role))) then
    raise exception 'INVALID_INPUT: pick a topic for the question';
  end if;
  if v_body is null then
    raise exception 'INVALID_INPUT: write your question';
  end if;
  perform private.support_rate_check(v_uid);
  if exists (select 1 from public.support_threads x where x.customer_id = v_uid and x.status <> 'closed') then
    raise exception 'INVALID_STATE: you already have an open conversation';
  end if;

  insert into public.support_threads (customer_id, category, opened_from, waiting_since)
  values (v_uid, p_category, left(nullif(btrim(p_opened_from), ''), 200), now())
  returning * into t;
  insert into public.support_messages (thread_id, sender_kind, sender_id, sender_name, body, image_path)
  values (t.id, 'customer', v_uid, private.person_name(v_uid), v_body, private.support_image(v_uid, p_image_path));
  return t;
end;
$$;

-- The studio asked whether it is sorted: yes closes it for good, no keeps it open (and waiting for staff).
create function public.support_answer_close(p_thread bigint, p_resolved boolean)
returns public.support_threads
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  t public.support_threads;
begin
  select * into t from public.support_threads where id = p_thread for update;
  if not found or t.customer_id is distinct from auth.uid() then
    raise exception 'NOT_FOUND: no such conversation';
  end if;
  if t.status <> 'closing' or p_resolved is null then
    raise exception 'INVALID_STATE: the studio has not asked to close this conversation';
  end if;

  if p_resolved then
    perform private.support_note(t.id, 'closed', auth.uid());
    update public.support_threads
       set status = 'closed', closed_at = now(), closed_by = 'customer', waiting_since = null, customer_read_at = now()
     where id = t.id
    returning * into t;
    perform private.support_log(t, 'closed', jsonb_build_object('by', 'customer'));
  else
    perform private.support_note(t.id, 'kept_open', auth.uid());
    update public.support_threads
       set status = 'open', close_asked_at = null, close_asked_by = null, waiting_since = now(),
           last_message_at = now(), customer_read_at = now()
     where id = t.id
    returning * into t;
  end if;
  return t;
end;
$$;

-- Their conversations, newest first (the open one on top), with what they haven't read and the last message.
create function public.support_my_threads()
returns table (id bigint, category text, status text, created_at timestamptz, last_message_at timestamptz,
               closed_at timestamptz, closed_by text, unread integer, last_sender_kind text, last_body text,
               last_event text, last_has_image boolean)
language sql
stable
security definer
set search_path = ''
as $$
  select t.id, t.category, t.status, t.created_at, t.last_message_at, t.closed_at, t.closed_by,
         private.support_unread_for_customer(t.id, t.customer_read_at),
         l.sender_kind, l.body, l.event, l.image_path is not null
    from public.support_threads t
    left join lateral (select m.sender_kind, m.body, m.event, m.image_path from public.support_messages m
                        where m.thread_id = t.id order by m.id desc limit 1) l on true
   where t.customer_id = auth.uid()
   order by (t.status <> 'closed') desc, t.last_message_at desc
   limit 50;
$$;

