-- Tables
-- -----------------------------------------------------------------------------
create table public.support_threads (
  id               bigint generated by default as identity primary key,
  customer_id      uuid not null references public.profiles (id) on delete cascade,
  category         text not null check (category in ('booking', 'classes', 'tuition', 'absence', 'account',
                                                     'checkin', 'payroll', 'cover', 'teaching', 'other')),
  status           text not null default 'open' check (status in ('open', 'closing', 'closed')),
  assigned_to      uuid references public.profiles (id) on delete set null,
  opened_from      text check (char_length(opened_from) <= 200),   -- the page the question was asked on
  created_at       timestamptz not null default now(),
  last_message_at  timestamptz not null default now(),
  waiting_since    timestamptz,
  close_asked_at   timestamptz,
  close_asked_by   uuid references public.profiles (id) on delete set null,
  closed_at        timestamptz,
  closed_by        text check (closed_by in ('customer', 'system')),
  customer_read_at timestamptz not null default now(),
  staff_read_at    timestamptz,
  constraint support_threads_closed check ((status = 'closed') = (closed_at is not null and closed_by is not null)),
  constraint support_threads_closing check (status <> 'closing' or close_asked_at is not null)
);
create unique index support_threads_one_open on public.support_threads (customer_id) where status <> 'closed';
create index support_threads_customer_idx on public.support_threads (customer_id, created_at desc);
create index support_threads_waiting_idx on public.support_threads (waiting_since) where status <> 'closed';
create index support_threads_closed_idx on public.support_threads (closed_at desc) where status = 'closed';

create table public.support_messages (
  id          bigint generated by default as identity primary key,
  thread_id   bigint not null references public.support_threads (id) on delete cascade,
  sender_kind text not null check (sender_kind in ('customer', 'staff', 'system', 'ai')),
  sender_id   uuid references public.profiles (id) on delete set null,
  sender_name text,                  -- as it was then (realtime rows arrive without joins)
  body        text check (char_length(body) between 1 and 2000),
  image_path  text check (char_length(image_path) <= 200),
  event       text check (event in ('close_asked', 'kept_open', 'closed', 'auto_closed', 'paused')),
  created_at  timestamptz not null default now(),
  constraint support_messages_shape check (
    case when sender_kind = 'system' then event is not null and body is null and image_path is null
         else event is null and (body is not null or image_path is not null) end)
);
create index support_messages_thread_idx on public.support_messages (thread_id, id);
create index support_messages_sender_idx on public.support_messages (sender_id, created_at desc);

alter table public.support_threads enable row level security;
alter table public.support_messages enable row level security;
create policy support_threads_select on public.support_threads
  for select to authenticated using (customer_id = (select auth.uid()) or public.is_staff());
create policy support_messages_select on public.support_messages
  for select to authenticated using (exists (
    select 1 from public.support_threads t
     where t.id = thread_id and (t.customer_id = (select auth.uid()) or public.is_staff())));
revoke all on public.support_threads, public.support_messages from anon;
revoke insert, update, delete, truncate, references, trigger on public.support_threads, public.support_messages from authenticated;
grant select on public.support_threads, public.support_messages to authenticated;

