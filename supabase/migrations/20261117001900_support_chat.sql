-- The Inbox. p_tab: 'waiting' (the person waits for the studio, longest first) | 'answered' (the studio
-- spoke last or asked to close, latest first) | 'closed' (latest 100). p_category narrows it.
create function public.support_inbox(p_tab text default 'waiting', p_category text default null)
returns table (id bigint, customer_id uuid, customer_name text, customer_role public.app_role, customer_avatar text,
               category text, status text, assigned_to uuid, assigned_name text, waiting_since timestamptz,
               last_message_at timestamptz, created_at timestamptz, closed_at timestamptz, closed_by text,
               opened_from text, unread integer, last_sender_kind text, last_body text, last_event text,
               last_has_image boolean)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.is_staff() then
    raise exception 'FORBIDDEN: only admins and staff read the Inbox';
  end if;
  if p_tab is null or p_tab not in ('waiting', 'answered', 'closed') then
    raise exception 'INVALID_INPUT: the Inbox tab is waiting, answered or closed';
  end if;
  return query
  select t.id, t.customer_id, private.person_name(t.customer_id), p.role, p.avatar_path,
         t.category, t.status, t.assigned_to, private.person_name(t.assigned_to), t.waiting_since,
         t.last_message_at, t.created_at, t.closed_at, t.closed_by, t.opened_from,
         private.support_unread_for_staff(t.id, t.staff_read_at),
         l.sender_kind, l.body, l.event, l.image_path is not null
    from public.support_threads t
    join public.profiles p on p.id = t.customer_id
    left join lateral (select m.sender_kind, m.body, m.event, m.image_path from public.support_messages m
                        where m.thread_id = t.id and m.event is distinct from 'paused'
                        order by m.id desc limit 1) l on true
   where (p_category is null or t.category = p_category)
     and case p_tab
           when 'waiting'  then t.status <> 'closed' and t.waiting_since is not null
           when 'answered' then t.status <> 'closed' and t.waiting_since is null
           else t.status = 'closed'
         end
   order by case when p_tab = 'waiting' then t.waiting_since end asc,
            case when p_tab = 'answered' then t.last_message_at end desc,
            case when p_tab = 'closed' then t.closed_at end desc
   limit case when p_tab = 'closed' then 100 else 500 end;
end;
$$;

-- For the to-do bell and the menu badge → { waiting, oldest_waiting_since, mine, answered }.
create function public.support_counts()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.is_staff() then
    raise exception 'FORBIDDEN: only admins and staff read the Inbox';
  end if;
  return (
    select jsonb_build_object(
             'waiting', count(*) filter (where t.waiting_since is not null),
             'oldest_waiting_since', min(t.waiting_since),
             'mine', count(*) filter (where t.waiting_since is not null and t.assigned_to = auth.uid()),
             'answered', count(*) filter (where t.waiting_since is null))
      from public.support_threads t where t.status <> 'closed');
end;
$$;

-- Take a conversation (p_staff null = yourself) or hand it to another staff member.
create function public.support_claim(p_thread bigint, p_staff uuid default null)
returns public.support_threads
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_to uuid := coalesce(p_staff, auth.uid());
  v_from uuid;
  t public.support_threads;
begin
  if not public.is_staff() then
    raise exception 'FORBIDDEN: only admins and staff take conversations';
  end if;
  if not exists (select 1 from public.profiles p where p.id = v_to and p.role in ('admin', 'staff')) then
    raise exception 'INVALID_INPUT: hand the conversation to a staff member or an admin';
  end if;
  select * into t from public.support_threads where id = p_thread for update;
  if not found then
    raise exception 'NOT_FOUND: no such conversation';
  end if;
  if t.status = 'closed' then
    raise exception 'INVALID_STATE: this conversation is closed';
  end if;
  if t.assigned_to = v_to then
    return t;
  end if;
  v_from := t.assigned_to;
  update public.support_threads set assigned_to = v_to where id = t.id returning * into t;
  perform private.support_log(t, case when v_to = auth.uid() then 'claimed' else 'handed_over' end,
                              jsonb_build_object('to', private.person_name(v_to), 'from', private.person_name(v_from)));
  return t;
end;
$$;

-- Ask the person whether it is sorted (they close it, or it closes by itself after 24 hours).
create function public.support_request_close(p_thread bigint)
returns public.support_threads
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  t public.support_threads;
begin
  if not public.is_staff() then
    raise exception 'FORBIDDEN: only admins and staff close conversations';
  end if;
  select * into t from public.support_threads where id = p_thread for update;
  if not found then
    raise exception 'NOT_FOUND: no such conversation';
  end if;
  if t.status = 'closing' then
    return t;
  end if;
  if t.status <> 'open' then
    raise exception 'INVALID_STATE: this conversation is closed';
  end if;
  if private.support_phase(now()) = 'closed' then
    raise exception 'SUPPORT_CLOSED: %', private.support_hours_text('answer');
  end if;

  perform private.support_note(t.id, 'close_asked', auth.uid());
  update public.support_threads
     set status = 'closing', close_asked_at = now(), close_asked_by = auth.uid(), waiting_since = null,
         last_message_at = now(), staff_read_at = now(), assigned_to = coalesce(assigned_to, auth.uid())
   where id = t.id
  returning * into t;
  perform private.support_log(t, 'close_asked');
  return t;
end;
$$;

-- Next to a conversation: who is asking → { id, name, email, phone, role, avatar_path, joined,
--   classes: [{ id, name }], unpaid: { count, amount }, bookings: [{ id, date, start, end, room, status }], conversations }.
create function public.support_customer_card(p_customer uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_today date := public.studio_today();
begin
  if not public.is_staff() then
    raise exception 'FORBIDDEN: only admins and staff read the Inbox';
  end if;
  return (
    select jsonb_build_object(
             'id', p.id, 'name', private.person_name(p.id), 'email', p.email, 'phone', p.contact_number,
             'role', p.role, 'avatar_path', p.avatar_path, 'joined', p.created_at,
             'classes', coalesce((
               select jsonb_agg(jsonb_build_object('id', c.id, 'name', c.name, 'teaches', c.teaches) order by c.name)
                 from (select c.id, c.name, false as teaches
                         from public.class_students cs join public.classes c on c.id = cs.class_id
                        where cs.student_id = p.id and (c.ended_on is null or c.ended_on >= v_today)
                       union
                       select c.id, c.name, true
                         from public.classes c
                        where c.instructor_id = p.id and (c.ended_on is null or c.ended_on >= v_today)) c), '[]'::jsonb),
             'unpaid', (select jsonb_build_object('count', count(*), 'amount', coalesce(sum(i.amount - i.paid_amount), 0))
                          from public.tuition_invoices i where i.student_id = p.id and i.status = 'unpaid'),
             'bookings', coalesce((
               select jsonb_agg(jsonb_build_object('id', b.id, 'date', b.date, 'start', b.start_time, 'end', b.end_time,
                                                   'room', b.room, 'status', b.status) order by b.date, b.start_time)
                 from (select b.id, b.date, b.start_time, b.end_time, r.name as room, b.status
                         from public.bookings b left join public.rooms r on r.id = b.room_id
                        where b.guest_id = p.id and b.date >= v_today and b.status in ('pending', 'approved')
                        order by b.date, b.start_time limit 5) b), '[]'::jsonb),
             'conversations', (select count(*) from public.support_threads t where t.customer_id = p.id))
      from public.profiles p where p.id = p_customer);
end;
$$;

-- -----------------------------------------------------------------------------
-- The job (every 5 minutes): unanswered close requests close after 24 hours; at closing time each
-- conversation active since opening time gets its night note. p_at is for tests. → { closed, paused }
-- -----------------------------------------------------------------------------
create function public.support_run(p_at timestamptz default now())
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  t public.support_threads;
  v_closed integer := 0;
  v_paused integer := 0;
  v_opens time;
  v_local timestamp := p_at at time zone 'Asia/Ho_Chi_Minh';
  v_since timestamptz;
begin
  if not private.is_service_context() then
    raise exception 'FORBIDDEN: the chat job runs on the server';
  end if;

  for t in select * from public.support_threads
            where status = 'closing' and close_asked_at <= p_at - interval '24 hours'
            order by id for update
  loop
    perform private.support_note(t.id, 'auto_closed');
    update public.support_threads
       set status = 'closed', closed_at = p_at, closed_by = 'system', waiting_since = null
     where id = t.id
    returning * into t;
    perform private.support_log(t, 'closed', jsonb_build_object('by', 'system'));
    v_closed := v_closed + 1;
  end loop;

  if private.support_phase(p_at) = 'closed' then
    select s.support_opens into v_opens from public.site_settings s where s.id = 1;
    -- The latest opening time at or before p_at.
    v_since := ((v_local::date - case when v_local::time >= v_opens then 0 else 1 end) + v_opens) at time zone 'Asia/Ho_Chi_Minh';
    insert into public.support_messages (thread_id, sender_kind, event)
    select t2.id, 'system', 'paused'
      from public.support_threads t2
     where t2.status <> 'closed' and t2.last_message_at >= v_since and t2.last_message_at <= p_at
       and (select m.event from public.support_messages m where m.thread_id = t2.id order by m.id desc limit 1)
           is distinct from 'paused';
    get diagnostics v_paused = row_count;
  end if;

  return jsonb_build_object('closed', v_closed, 'paused', v_paused);
end;
$$;

select cron.schedule('support-run', '*/5 * * * *', $$select public.support_run()$$);

