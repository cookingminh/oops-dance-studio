-- Chat with the studio (api-contract §3 support_threads / support_messages, §5 Support chat).
--
-- Signed-in students, room guests and instructors ask the studio a question from the bubble on every page;
-- staff and admins answer from the Inbox. One conversation is one request:
--   * Hours (site_settings, studio time; default 08:00 / 21:45 / 22:00):
--       support_opens ≤ t < support_last_start   'open'       new conversations and messages;
--       support_last_start ≤ t < support_closes  'last_call'  only conversations already open go on;
--       otherwise                                'closed'     nobody writes, staff included.
--     At closing time, a conversation that was active since opening time gets a system note ('paused':
--     "staff carry on from 08:00") and stays open; it is first in the Inbox in the morning (support_run, every 5 min).
--   * One conversation per person at a time: status open | closing | closed.
--   * Closing: staff ask (support_request_close → 'closing'); the person answers (support_answer_close):
--     resolved → 'closed' for good (a new question is a new conversation), not yet → 'open' again. Writing a
--     message while asked counts as "not yet". No answer within 24 hours → closed by the system.
--   * waiting_since: when the person started waiting for the studio (null = the studio spoke last).
--   * sender_kind customer | staff | system | ai ('ai' is reserved for a future assistant; nothing writes it yet).
--     System messages carry an `event` instead of text (the app words them in the reader's language).
--   * Photos: private bucket support-images, path {person_id}/{file}; that person and staff read them.
--   * RLS: a person reads their own conversations and messages, staff and admins read all of them; every
--     write goes through the RPCs below. Both tables are published to Supabase Realtime (RLS applies).
--   * The Activity page (area 'support') gets claimed / handed_over / close_asked / closed, never message text.

-- -----------------------------------------------------------------------------
-- Hours
-- -----------------------------------------------------------------------------
alter table public.site_settings
  add column support_opens      time not null default '08:00',
  add column support_last_start time not null default '21:45',
  add column support_closes     time not null default '22:00',
  add constraint site_settings_support_hours
    check (support_opens <= support_last_start and support_last_start <= support_closes);

-- 'open' | 'last_call' | 'closed' at p_at (studio time).
create function private.support_phase(p_at timestamptz default now())
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select case
           when x.t >= s.support_opens and x.t < s.support_last_start then 'open'
           when x.t >= s.support_last_start and x.t < s.support_closes then 'last_call'
           else 'closed'
         end
    from public.site_settings s
   cross join lateral (select (p_at at time zone 'Asia/Ho_Chi_Minh')::time as t) x
   where s.id = 1;
$$;

-- The topics a person picks from: students and room guests, or instructors.
create function private.support_categories(p_role public.app_role)
returns text[]
language sql
immutable
set search_path = ''
as $$
  select case p_role
           when 'guest'      then array['booking', 'classes', 'tuition', 'absence', 'account', 'other']
           when 'instructor' then array['checkin', 'payroll', 'cover', 'teaching', 'account', 'other']
           else array[]::text[]
         end;
$$;

