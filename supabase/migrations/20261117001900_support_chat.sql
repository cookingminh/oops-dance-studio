-- A person's own folder; staff every folder (they attach photos to someone's conversation).
create function private.can_access_support_image(p_name text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select auth.uid() is not null
     and coalesce(p_name, '') ~ '^[0-9a-f-]{36}/[A-Za-z0-9._-]{1,120}$'
     and (public.is_staff() or split_part(p_name, '/', 1) = auth.uid()::text);
$$;
revoke execute on function private.can_access_support_image(text) from public, anon;
grant execute on function private.can_access_support_image(text) to authenticated;

