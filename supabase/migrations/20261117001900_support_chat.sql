-- Write in a conversation. The person: until closing time (writing while asked to close = "not yet").
-- Staff: until closing time too; the first staff member to reply takes the conversation.
create function public.support_send(p_thread bigint, p_body text, p_image_path text default null)
returns public.support_messages
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_body text := private.support_body(p_body);
  t public.support_threads;
  m public.support_messages;
  v_customer boolean;
begin
  select * into t from public.support_threads where id = p_thread for update;
  if not found or v_uid is null or not (t.customer_id = v_uid or public.is_staff()) then
    raise exception 'NOT_FOUND: no such conversation';
  end if;
  v_customer := t.customer_id = v_uid;
  if t.status = 'closed' then
    raise exception 'INVALID_STATE: this conversation is closed; ask a new question';
  end if;
  if private.support_phase(now()) = 'closed' then
    raise exception 'SUPPORT_CLOSED: %', private.support_hours_text('answer');
  end if;
  if v_body is null and p_image_path is null then
    raise exception 'INVALID_INPUT: write a message';
  end if;

  if v_customer then
    perform private.support_rate_check(v_uid);
    if t.status = 'closing' then
      perform private.support_note(t.id, 'kept_open', v_uid);
    end if;
  end if;

  insert into public.support_messages (thread_id, sender_kind, sender_id, sender_name, body, image_path)
  values (t.id, case when v_customer then 'customer' else 'staff' end, v_uid, private.person_name(v_uid), v_body,
          private.support_image(t.customer_id, p_image_path))
  returning * into m;

  if v_customer then
    update public.support_threads
       set status = 'open', close_asked_at = null, close_asked_by = null,
           waiting_since = coalesce(waiting_since, now()), last_message_at = now(), customer_read_at = now()
     where id = t.id;
  else
    v_customer := t.assigned_to is null;   -- (reused: nobody had it yet)
    update public.support_threads
       set waiting_since = null, last_message_at = now(), staff_read_at = now(), assigned_to = coalesce(assigned_to, v_uid)
     where id = t.id
    returning * into t;
    if v_customer then
      perform private.support_log(t, 'claimed', jsonb_build_object('auto', true, 'to', private.person_name(v_uid)));
    end if;
  end if;
  return m;
end;
$$;

-- Opened the conversation: what's in it now counts as read (by the person, or by the studio).
create function public.support_mark_read(p_thread bigint)
returns void
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  t public.support_threads;
begin
  select * into t from public.support_threads where id = p_thread;
  if not found or auth.uid() is null or not (t.customer_id = auth.uid() or public.is_staff()) then
    raise exception 'NOT_FOUND: no such conversation';
  end if;
  if t.customer_id = auth.uid() then
    update public.support_threads set customer_read_at = now() where id = t.id;
  else
    update public.support_threads set staff_read_at = now() where id = t.id;
  end if;
end;
$$;

