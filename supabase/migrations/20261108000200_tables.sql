-- -----------------------------------------------------------------------------
-- bookings
-- -----------------------------------------------------------------------------
create table public.bookings (
  id             bigint generated by default as identity primary key,
  room_id        bigint not null references public.rooms (id),
  guest_id       uuid not null references public.profiles (id),
  date           date not null,
  start_time     time not null,
  end_time       time not null,
  status         public.booking_status not null default 'pending',
  deposit        numeric(12, 0) check (deposit >= 0),
  full_payment   numeric(12, 0) check (full_payment >= 0),
  real_income    numeric(12, 0) check (real_income >= 0),
  bank_transfer  numeric(12, 0) check (bank_transfer >= 0),
  cash           numeric(12, 0) check (cash >= 0),
  deposit_status public.deposit_status not null default 'waiting',
  details        text,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  constraint bookings_time_order check (end_time > start_time),
  constraint bookings_opening_hours check (start_time >= time '08:00' and end_time <= time '22:00'),
  constraint bookings_half_hour_grid check (
    extract(minute from start_time) in (0, 30) and extract(second from start_time) = 0
    and extract(minute from end_time) in (0, 30) and extract(second from end_time) = 0
  ),
  -- Same room, overlapping [start, end) on the same date, while the booking is live.
  constraint bookings_no_overlap exclude using gist (
    room_id with =,
    tsrange(date + start_time, date + end_time, '[)') with &&
  ) where (status in ('pending', 'approved'))
);
create index bookings_room_id_date_idx on public.bookings (room_id, date);
create index bookings_guest_id_idx on public.bookings (guest_id);
create index bookings_date_idx on public.bookings (date);

