-- classes.instructor_id must point at a profile with role 'instructor'.
create or replace function private.enforce_class_instructor_role()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not exists (
    select 1 from public.profiles p
    where p.id = new.instructor_id and p.role = 'instructor'
  ) then
    raise exception 'INVALID_INPUT: instructor_id must reference a profile with role instructor';
  end if;
  return new;
end;
$$;

create trigger enforce_class_instructor_role
  before insert or update of instructor_id on public.classes
  for each row execute function private.enforce_class_instructor_role();

-- Room timetable writes (bookings, class schedules, class room changes) take
-- this per-room transaction lock so two concurrent writes cannot both pass
-- the cross-table overlap checks below.
create or replace function private.lock_room(p_room_id bigint)
returns void
language sql
volatile
security definer
set search_path = ''
as $$
  select pg_advisory_xact_lock(hashtextextended('oops.room:' || p_room_id::text, 0));
$$;

-- Booking rules for every write path (create_booking and staff table writes):
--   * INVALID_INPUT: end <= start, outside 08:00–22:00, not on the 30-minute grid
--     (checked here so callers get the contract code; the CHECK constraints
--     above stay as the backstop)
--   * SLOT_TAKEN: a live booking may not overlap a class scheduled in the same
--     room on that weekday. Booking-vs-booking overlap is bookings_no_overlap.
create or replace function private.check_booking_rules()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_class text;
begin
  if new.end_time <= new.start_time then
    raise exception 'INVALID_INPUT: end time must be after start time';
  end if;
  if new.start_time < time '08:00' or new.end_time > time '22:00' then
    raise exception 'INVALID_INPUT: bookings must be between 08:00 and 22:00';
  end if;
  if extract(minute from new.start_time) not in (0, 30) or extract(second from new.start_time) <> 0
     or extract(minute from new.end_time) not in (0, 30) or extract(second from new.end_time) <> 0
  then
    raise exception 'INVALID_INPUT: start and end must be on the half hour (HH:00 or HH:30)';
  end if;

  if new.status in ('pending', 'approved') then
    perform private.lock_room(new.room_id);
    select c.name into v_class
    from public.class_schedules s
    join public.classes c on c.id = s.class_id
    where c.room_id = new.room_id
      and s.day_of_week = extract(isodow from new.date)
      and s.start_time < new.end_time
      and s.end_time > new.start_time
    limit 1;
    if found then
      raise exception 'SLOT_TAKEN: the room is reserved for class "%" at that time', v_class;
    end if;
  end if;
  return new;
end;
$$;

create trigger check_booking_rules
  before insert or update of room_id, date, start_time, end_time, status on public.bookings
  for each row execute function private.check_booking_rules();

-- A class schedule may not overlap
--   * another schedule (any class, including the same one) in the same room on
--     the same weekday, nor
--   * a pending/approved booking in that room dated today or later on that weekday.
-- Raises SLOT_TAKEN. Used for schedule writes and for moving a class to a room.
-- The row itself is skipped by id and by its unique key (class, weekday, start):
-- in INSERT … ON CONFLICT the BEFORE INSERT trigger runs before the conflict is
-- detected, so an upsert of an existing schedule must not clash with itself.
create or replace function private.assert_schedule_slot_free(
  p_room_id     bigint,
  p_schedule_id bigint,
  p_class_id    bigint,
  p_day_of_week smallint,
  p_start       time,
  p_end         time
)
returns void
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_other record;
begin
  if p_room_id is null then
    return;  -- a class without a room blocks nothing
  end if;
  perform private.lock_room(p_room_id);

  select c.name, s.start_time, s.end_time into v_other
  from public.class_schedules s
  join public.classes c on c.id = s.class_id
  where c.room_id = p_room_id
    and s.day_of_week = p_day_of_week
    and s.id is distinct from p_schedule_id
    and not (s.class_id = p_class_id and s.start_time = p_start)
    and s.start_time < p_end
    and s.end_time > p_start
  limit 1;
  if found then
    raise exception 'SLOT_TAKEN: overlaps class "%" (%–%) in the same room',
      v_other.name, to_char(v_other.start_time, 'HH24:MI'), to_char(v_other.end_time, 'HH24:MI');
  end if;

  select b.date, b.start_time, b.end_time into v_other
  from public.bookings b
  where b.room_id = p_room_id
    and b.status in ('pending', 'approved')
    and b.date >= public.studio_today()
    and extract(isodow from b.date) = p_day_of_week
    and b.start_time < p_end
    and b.end_time > p_start
  order by b.date
  limit 1;
  if found then
    raise exception 'SLOT_TAKEN: overlaps a booking on % (%–%)',
      v_other.date, to_char(v_other.start_time, 'HH24:MI'), to_char(v_other.end_time, 'HH24:MI');
  end if;
end;
$$;

create or replace function private.check_class_schedule_slot()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform private.assert_schedule_slot_free(
    (select c.room_id from public.classes c where c.id = new.class_id),
    new.id, new.class_id, new.day_of_week, new.start_time, new.end_time);
  return new;
end;
$$;

create trigger check_class_schedule_slot
  before insert or update of class_id, day_of_week, start_time, end_time on public.class_schedules
  for each row execute function private.check_class_schedule_slot();

-- Moving a class to another room re-checks each of its schedules there.
create or replace function private.check_class_room_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  s record;
begin
  -- Schedules of a room-less class were never checked against each other.
  if exists (
    select 1
    from public.class_schedules a
    join public.class_schedules b
      on b.class_id = a.class_id and b.day_of_week = a.day_of_week and b.id > a.id
     and b.start_time < a.end_time and b.end_time > a.start_time
    where a.class_id = new.id
  ) then
    raise exception 'SLOT_TAKEN: class "%" has overlapping schedules of its own', new.name;
  end if;

  for s in select * from public.class_schedules cs where cs.class_id = new.id loop
    perform private.assert_schedule_slot_free(new.room_id, s.id, s.class_id, s.day_of_week, s.start_time, s.end_time);
  end loop;
  return new;
end;
$$;

create trigger check_class_room_change
  before update of room_id on public.classes
  for each row
  when (new.room_id is distinct from old.room_id and new.room_id is not null)
  execute function private.check_class_room_change();

-- Instructors may only change status/details of student_attendance rows
-- (RLS limits which rows; this limits which columns).
create or replace function private.guard_student_attendance_update()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not private.is_service_context()
     and not public.is_staff()
     and (new.class_id, new.student_id, new.date) is distinct from (old.class_id, old.student_id, old.date)
  then
    raise exception 'FORBIDDEN: only status and details can be changed';
  end if;
  return new;
end;
$$;

create trigger guard_student_attendance_update
  before update on public.student_attendance
  for each row execute function private.guard_student_attendance_update();

