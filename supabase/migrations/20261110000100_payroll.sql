-- -----------------------------------------------------------------------------
-- Payroll (admin only)
--
--   Instructors are paid per session: every instructor_attendance row of the month whose status
--   is 'completed' (checked in + out with proofs, or marked completed by staff) counts once, at
--   the class's rate (class_pay_rates) or the studio default (payroll_settings, 300,000 VND).
--   Office staff (and any admin given a salary) get a fixed monthly salary (staff_salaries).
--   Admins add bonuses (+) and deductions (−), each with a reason (payroll_adjustments).
--
--   A person's month is a live draft until an admin finalizes it: payroll_finalize() stores a
--   snapshot in payslips (status 'finalized') and locks that month's adjustments. It can be
--   reopened (back to draft) until it is marked 'paid'.
--
--   Rates live outside `classes` on purpose: classes are publicly readable, pay is not.
--   The RPCs accept admins and the service role (seed scripts); RLS keeps the tables admin-only.
-- -----------------------------------------------------------------------------

create table public.payroll_settings (
  id                   smallint primary key default 1 check (id = 1),
  default_session_rate numeric(12, 0) not null default 300000 check (default_session_rate >= 0),
  updated_at           timestamptz not null default now()
);
insert into public.payroll_settings (id) values (1);

create table public.class_pay_rates (
  class_id     bigint primary key references public.classes (id) on delete cascade,
  session_rate numeric(12, 0) not null check (session_rate >= 0),
  updated_at   timestamptz not null default now()
);

create table public.staff_salaries (
  profile_id     uuid primary key references public.profiles (id) on delete cascade,
  monthly_salary numeric(12, 0) not null check (monthly_salary >= 0),
  updated_at     timestamptz not null default now()
);

create table public.payroll_adjustments (
  id            bigint generated by default as identity primary key,
  profile_id    uuid not null references public.profiles (id) on delete cascade,
  month         date not null check (month = date_trunc('month', month)::date),
  amount        numeric(12, 0) not null check (amount <> 0), -- > 0 bonus, < 0 deduction
  reason        text not null check (char_length(btrim(reason)) between 1 and 200),
  attendance_id bigint references public.instructor_attendance (id) on delete set null,
  created_by    uuid references public.profiles (id) on delete set null default auth.uid(),
  created_at    timestamptz not null default now()
);
create index payroll_adjustments_profile_month_idx on public.payroll_adjustments (profile_id, month);

create table public.payslips (
  profile_id   uuid not null references public.profiles (id) on delete cascade,
  month        date not null check (month = date_trunc('month', month)::date),
  status       text not null default 'finalized' check (status in ('finalized', 'paid')),
  sessions     integer not null default 0,
  session_pay  numeric(12, 0) not null default 0,
  base_salary  numeric(12, 0) not null default 0,
  bonuses      numeric(12, 0) not null default 0,
  deductions   numeric(12, 0) not null default 0, -- ≤ 0
  total        numeric(12, 0) not null,
  finalized_at timestamptz not null default now(),
  finalized_by uuid references public.profiles (id) on delete set null default auth.uid(),
  paid_at      timestamptz,
  primary key (profile_id, month),
  check ((status = 'paid') = (paid_at is not null))
);

create trigger set_updated_at before update on public.payroll_settings
  for each row execute function private.set_updated_at();
create trigger set_updated_at before update on public.class_pay_rates
  for each row execute function private.set_updated_at();
create trigger set_updated_at before update on public.staff_salaries
  for each row execute function private.set_updated_at();

-- A finalized (or paid) month is frozen: its adjustments can't change until it is reopened.
create or replace function private.guard_finalized_adjustments()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_row public.payroll_adjustments := coalesce(new, old);
begin
  if exists (select 1 from public.payslips s where s.profile_id = v_row.profile_id and s.month = v_row.month)
     or (tg_op = 'UPDATE' and exists (select 1 from public.payslips s where s.profile_id = old.profile_id and s.month = old.month))
  then
    raise exception 'INVALID_STATE: this month is finalized; reopen it to change bonuses or deductions';
  end if;
  return coalesce(new, old);
end;
$$;

create trigger guard_finalized_adjustments
  before insert or update or delete on public.payroll_adjustments
  for each row execute function private.guard_finalized_adjustments();

