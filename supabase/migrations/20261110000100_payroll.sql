-- -----------------------------------------------------------------------------
-- payroll_month(p_month): one row per person to pay for that month.
--   Everyone with role instructor or staff, plus anyone else with a salary, sessions,
--   adjustments or a payslip that month. A finalized/paid month shows its snapshot.
-- -----------------------------------------------------------------------------
create or replace function public.payroll_month(p_month date)
returns table (
  profile_id   uuid,
  full_name    text,
  username     text,
  email        text,
  avatar_path  text,
  updated_at   timestamptz,
  role         public.app_role,
  sessions     integer,
  session_pay  numeric,
  base_salary  numeric,
  bonuses      numeric,
  deductions   numeric,
  total        numeric,
  status       text,
  finalized_at timestamptz,
  paid_at      timestamptz
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_start date := date_trunc('month', p_month)::date;
  v_stop  date := (date_trunc('month', p_month) + interval '1 month')::date;
  v_rate  numeric := (select s.default_session_rate from public.payroll_settings s where s.id = 1);
begin
  if not (public.is_admin() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only an admin can see payroll';
  end if;

  return query
  with sess as (
    select a.instructor_id as pid,
           count(*)::integer as n,
           sum(coalesce(r.session_rate, v_rate)) as pay
      from public.instructor_attendance a
      left join public.class_pay_rates r on r.class_id = a.class_id
     where a.status = 'completed' and a.date >= v_start and a.date < v_stop
     group by a.instructor_id
  ), adj as (
    select a.profile_id as pid,
           sum(greatest(a.amount, 0)) as plus,
           sum(least(a.amount, 0)) as minus
      from public.payroll_adjustments a
     where a.month = v_start
     group by a.profile_id
  ), live as (
    select p.id,
           coalesce(sess.n, 0) as n,
           coalesce(sess.pay, 0) as pay,
           coalesce(sal.monthly_salary, 0) as base,
           coalesce(adj.plus, 0) as plus,
           coalesce(adj.minus, 0) as minus
      from public.profiles p
      left join sess on sess.pid = p.id
      left join adj on adj.pid = p.id
      left join public.staff_salaries sal on sal.profile_id = p.id
     where p.role in ('instructor', 'staff')
        or sal.profile_id is not null
        or sess.pid is not null
        or adj.pid is not null
        or exists (select 1 from public.payslips s where s.profile_id = p.id and s.month = v_start)
  )
  select p.id, p.full_name, p.username, p.email, p.avatar_path, p.updated_at, p.role,
         coalesce(s.sessions, l.n),
         coalesce(s.session_pay, l.pay),
         coalesce(s.base_salary, l.base),
         coalesce(s.bonuses, l.plus),
         coalesce(s.deductions, l.minus),
         coalesce(s.total, l.pay + l.base + l.plus + l.minus),
         coalesce(s.status, 'draft'),
         s.finalized_at,
         s.paid_at
    from live l
    join public.profiles p on p.id = l.id
    left join public.payslips s on s.profile_id = l.id and s.month = v_start
   order by p.role, p.full_name;
end;
$$;

-- Freeze a person's month: store the current numbers as their payslip.
create or replace function public.payroll_finalize(p_profile uuid, p_month date)
returns public.payslips
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_month date := date_trunc('month', p_month)::date;
  v_live  record;
  v_row   public.payslips;
begin
  if not (public.is_admin() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only an admin can finalize payroll';
  end if;
  if exists (select 1 from public.payslips s where s.profile_id = p_profile and s.month = v_month) then
    raise exception 'INVALID_STATE: this month is already finalized';
  end if;

  select * into v_live from public.payroll_month(v_month) m where m.profile_id = p_profile;
  if not found then
    raise exception 'NOT_FOUND: nobody to pay with this id in that month';
  end if;

  insert into public.payslips (profile_id, month, sessions, session_pay, base_salary, bonuses, deductions, total)
  values (p_profile, v_month, v_live.sessions, v_live.session_pay, v_live.base_salary, v_live.bonuses, v_live.deductions, v_live.total)
  returning * into v_row;
  return v_row;
end;
$$;

-- Back to draft (live numbers, adjustments editable). Not once paid.
create or replace function public.payroll_reopen(p_profile uuid, p_month date)
returns void
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_status text;
begin
  if not (public.is_admin() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only an admin can reopen payroll';
  end if;
  select s.status into v_status from public.payslips s
   where s.profile_id = p_profile and s.month = date_trunc('month', p_month)::date for update;
  if v_status is null then
    raise exception 'INVALID_STATE: this month is not finalized';
  end if;
  if v_status = 'paid' then
    raise exception 'INVALID_STATE: this month is already paid; mark it unpaid first';
  end if;
  delete from public.payslips s where s.profile_id = p_profile and s.month = date_trunc('month', p_month)::date;
end;
$$;

-- Mark a finalized month paid (p_paid = true) or undo it (false).
create or replace function public.payroll_set_paid(p_profile uuid, p_month date, p_paid boolean)
returns public.payslips
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_row public.payslips;
begin
  if not (public.is_admin() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only an admin can mark payroll paid';
  end if;
  update public.payslips s
     set status = case when p_paid then 'paid' else 'finalized' end,
         paid_at = case when p_paid then now() else null end
   where s.profile_id = p_profile and s.month = date_trunc('month', p_month)::date
     and s.status = case when p_paid then 'finalized' else 'paid' end
  returning * into v_row;
  if not found then
    raise exception 'INVALID_STATE: finalize the month first (or it is already in that state)';
  end if;
  return v_row;
end;
$$;

