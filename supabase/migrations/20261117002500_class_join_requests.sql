-- Asking to join a class (api-contract §3 class_join_requests, §5 Join requests).
--
-- A student (role guest) asks to join a class from /classes: from now (the running course, paying for the sessions
-- left) or from the next course, with a note. They are NOT added: staff or an admin approve or decline first.
--   * class_join_request: the student asks (one waiting request per class, up to 3 waiting at once).
--   * class_join_cancel: the student takes it back while it waits.
--   * class_join_approve (staff): adds them to class_students — now (joined today) or from the next planned course
--     (joined on its first day). The class_students triggers bill the course and put them on today's roll call,
--     exactly as when staff add a student from the class hub.
--   * class_join_decline (staff): with an optional reason the student sees.
-- Two things answer a request on their own:
--   * staff adding the student to the class directly (class hub, user manager, a class switch) approve it;
--   * the class ending (class_end sets ended_on) declines it, with the reason 'The class has ended.' (a UI key).
-- Students read their own requests, staff all of them; writes only go through the RPCs. Every step is on the
-- Activity page (area 'students', entity 'class_join_requests').

create type public.join_request_status as enum ('pending', 'approved', 'declined', 'cancelled');

create table public.class_join_requests (
  id             bigint generated by default as identity primary key,
  class_id       bigint not null references public.classes (id) on delete cascade,
  student_id     uuid not null constraint class_join_requests_student_id_fkey references public.profiles (id) on delete cascade,
  status         public.join_request_status not null default 'pending',
  start_pref     text not null default 'now' check (start_pref in ('now', 'next')),
  note           text check (char_length(note) <= 500),
  decided_by     uuid constraint class_join_requests_decided_by_fkey references public.profiles (id) on delete set null,
  decided_at     timestamptz,
  decline_reason text check (char_length(decline_reason) <= 300),
  joined_at      date,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  -- answered (or taken back) = has a time; only an approved request has a start date, only a declined one a reason
  constraint class_join_requests_decided check ((status = 'pending') = (decided_at is null)),
  constraint class_join_requests_joined check ((status = 'approved') = (joined_at is not null)),
  constraint class_join_requests_reason check (decline_reason is null or status = 'declined')
);
create unique index class_join_requests_one_pending on public.class_join_requests (class_id, student_id) where status = 'pending';
create index class_join_requests_class_idx on public.class_join_requests (class_id, created_at desc);
create index class_join_requests_student_idx on public.class_join_requests (student_id, created_at desc);
create index class_join_requests_pending_idx on public.class_join_requests (created_at) where status = 'pending';
create index class_join_requests_decided_by_idx on public.class_join_requests (decided_by) where decided_by is not null;

create trigger set_updated_at before update on public.class_join_requests
  for each row execute function private.set_updated_at();

alter table public.class_join_requests enable row level security;
create policy class_join_requests_select on public.class_join_requests for select to authenticated
  using (student_id = (select auth.uid()) or (select public.is_staff()));
revoke all on public.class_join_requests from anon;
revoke insert, update, delete, truncate, references, trigger on public.class_join_requests from authenticated;
grant select on public.class_join_requests to authenticated;

-- -----------------------------------------------------------------------------
-- Activity log: area 'students', the student as label and subject, the class's name in meta.
-- -----------------------------------------------------------------------------
create function private.join_log(r public.class_join_requests, p_action text, p_meta jsonb default '{}'::jsonb)
returns void
language sql
volatile
security definer
set search_path = ''
as $$
  insert into public.activity_log (actor_id, actor_name, actor_role, area, action, entity, entity_id, class_id, subject_id,
                                   label, meta)
  select auth.uid(), private.person_name(auth.uid()), (select p.role from public.profiles p where p.id = auth.uid()),
         'students', p_action, 'class_join_requests', r.id::text, r.class_id, r.student_id,
         coalesce(private.person_name(r.student_id), ''),
         nullif(jsonb_strip_nulls(jsonb_build_object('class', private.class_name(r.class_id)) || coalesce(p_meta, '{}'::jsonb)),
                '{}'::jsonb)
   where coalesce(current_setting('oops.activity', true), '') <> 'off';
$$;

-- -----------------------------------------------------------------------------
-- Student: ask to join a class. p_start 'now' (the running course) or 'next' (the next course); a note for staff.
-- -----------------------------------------------------------------------------
create function public.class_join_request(p_class_id bigint, p_start text default 'now', p_note text default null)
returns public.class_join_requests
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_me uuid := auth.uid();
  v_today date := public.studio_today();
  v_ended date;
  v_note text := nullif(btrim(p_note), '');
  r public.class_join_requests;
begin
  if (select p.role from public.profiles p where p.id = v_me) is distinct from 'guest' then
    raise exception 'FORBIDDEN: only students can ask to join a class';
  end if;
  select c.ended_on into v_ended from public.classes c where c.id = p_class_id;
  if not found then
    raise exception 'NOT_FOUND: class';
  end if;
  if v_ended is not null then
    raise exception 'INVALID_STATE: this class is not taking new students';
  end if;
  if p_start is null or p_start not in ('now', 'next') then
    raise exception 'INVALID_INPUT: start must be now or next';
  end if;
  if char_length(v_note) > 500 then
    raise exception 'INVALID_INPUT: the note is up to 500 characters';
  end if;

  -- One student's requests one at a time, so two quick clicks can't both pass the checks below.
  perform pg_advisory_xact_lock(hashtextextended('oops.join:' || v_me::text, 0));
  if exists (select 1 from public.class_students cs
              where cs.class_id = p_class_id and cs.student_id = v_me
                and (cs.leaves_after is null or cs.leaves_after >= v_today)) then
    raise exception 'INVALID_STATE: already in this class';
  end if;
  if exists (select 1 from public.class_join_requests q
              where q.class_id = p_class_id and q.student_id = v_me and q.status = 'pending') then
    raise exception 'INVALID_STATE: already asked to join this class';
  end if;
  if (select count(*) from public.class_join_requests q where q.student_id = v_me and q.status = 'pending') >= 3 then
    raise exception 'INVALID_STATE: too many open requests';
  end if;

  insert into public.class_join_requests (class_id, student_id, start_pref, note)
  values (p_class_id, v_me, p_start, v_note)
  returning * into r;
  perform private.join_log(r, 'join_requested', jsonb_build_object('start', r.start_pref, 'note', r.note));
  return r;
end;
$$;

-- -----------------------------------------------------------------------------
-- Student: take back their own request while it waits.
-- -----------------------------------------------------------------------------
create function public.class_join_cancel(p_request bigint)
returns public.class_join_requests
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  r public.class_join_requests;
begin
  select * into r from public.class_join_requests q
   where q.id = p_request and q.student_id = auth.uid()
     for update;
  if not found then
    raise exception 'NOT_FOUND: request';
  end if;
  if r.status <> 'pending' then
    raise exception 'INVALID_STATE: this request is no longer waiting';
  end if;

  update public.class_join_requests
     set status = 'cancelled', decided_by = auth.uid(), decided_at = now()
   where id = r.id
  returning * into r;
  perform private.join_log(r, 'join_cancelled');
  return r;
end;
$$;

-- -----------------------------------------------------------------------------
-- Staff: approve. p_from 'now' (joins today: billed for the sessions left of the running course) or 'next'
-- (joins on the next planned course's first day: billed for that course in full); null = what the student asked.
-- Someone already in the class (added meanwhile) keeps their place and start date.
-- -----------------------------------------------------------------------------
create function public.class_join_approve(p_request bigint, p_from text default null)
returns public.class_join_requests
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_today date := public.studio_today();
  v_from text;
  v_joined date;
  v_member public.class_students;
  v_had_row boolean;
  v_in boolean;
  r public.class_join_requests;
begin
  if not (public.is_staff() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only staff can answer a join request';
  end if;
  select * into r from public.class_join_requests q where q.id = p_request for update;
  if not found then
    raise exception 'NOT_FOUND: request';
  end if;
  if r.status <> 'pending' then
    raise exception 'INVALID_STATE: this request is no longer waiting';
  end if;
  if (select c.ended_on from public.classes c where c.id = r.class_id) is not null then
    raise exception 'INVALID_STATE: this class is not taking new students';
  end if;
  v_from := coalesce(p_from, r.start_pref);
  if v_from not in ('now', 'next') then
    raise exception 'INVALID_INPUT: start must be now or next';
  end if;

  select * into v_member from public.class_students cs
   where cs.class_id = r.class_id and cs.student_id = r.student_id
     for update;
  v_had_row := found;
  v_in := v_had_row and (v_member.leaves_after is null or v_member.leaves_after >= v_today);
  if v_in then
    v_joined := v_member.joined_at;  -- already in the class (added meanwhile): nothing to add
  else
    v_joined := case v_from
      when 'now' then v_today
      -- the next course: the earliest routine the class hub shows as planned (lesson_progress)
      else (select min(lp.starts_on) from public.lesson_progress(array[r.class_id]) lp where lp.status = 'planned') end;
    if v_joined is null then
      raise exception 'INVALID_INPUT: this class has no next course planned';
    end if;
  end if;

  -- The request first, so the class_students trigger below finds nothing waiting.
  update public.class_join_requests
     set status = 'approved', decided_by = auth.uid(), decided_at = now(), joined_at = v_joined
   where id = r.id
  returning * into r;
  perform private.join_log(r, 'join_approved', jsonb_build_object('start', v_from, 'joined_at', v_joined));

  if not v_in then
    if v_had_row then
      -- they had left (the nightly cycle hasn't removed them yet): out, then back in from the new start
      delete from public.class_students cs where cs.class_id = r.class_id and cs.student_id = r.student_id;
    end if;
    -- billing (on_enrolment_added) and today's roll call (enrolment_catch_up) follow from the triggers
    insert into public.class_students (class_id, student_id, joined_at) values (r.class_id, r.student_id, v_joined);
  end if;
  return r;
end;
$$;

-- -----------------------------------------------------------------------------
-- Staff: decline, with an optional reason the student sees.
-- -----------------------------------------------------------------------------
create function public.class_join_decline(p_request bigint, p_reason text default null)
returns public.class_join_requests
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_reason text := nullif(btrim(p_reason), '');
  r public.class_join_requests;
begin
  if not (public.is_staff() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only staff can answer a join request';
  end if;
  select * into r from public.class_join_requests q where q.id = p_request for update;
  if not found then
    raise exception 'NOT_FOUND: request';
  end if;
  if r.status <> 'pending' then
    raise exception 'INVALID_STATE: this request is no longer waiting';
  end if;
  if char_length(v_reason) > 300 then
    raise exception 'INVALID_INPUT: the reason is up to 300 characters';
  end if;

  update public.class_join_requests
     set status = 'declined', decided_by = auth.uid(), decided_at = now(), decline_reason = v_reason
   where id = r.id
  returning * into r;
  perform private.join_log(r, 'join_declined', jsonb_build_object('reason', v_reason));
  return r;
end;
$$;

-- -----------------------------------------------------------------------------
-- Answered on their own
-- -----------------------------------------------------------------------------
-- Staff added the student to the class directly: their waiting request is approved, from the day they joined.
create function private.join_request_enrolled()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  r public.class_join_requests;
begin
  for r in
    update public.class_join_requests q
       set status = 'approved', decided_by = auth.uid(), decided_at = now(), joined_at = new.joined_at
     where q.class_id = new.class_id and q.student_id = new.student_id and q.status = 'pending'
    returning q.*
  loop
    perform private.join_log(r, 'join_approved', jsonb_build_object('joined_at', r.joined_at));
  end loop;
  return null;
end;
$$;

create trigger approve_join_request after insert on public.class_students
  for each row execute function private.join_request_enrolled();

-- The class ends (or is set to end): nobody new joins, so its waiting requests are declined.
create function private.join_requests_class_ended()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  r public.class_join_requests;
begin
  for r in
    update public.class_join_requests q
       set status = 'declined', decided_by = auth.uid(), decided_at = now(), decline_reason = 'The class has ended.'
     where q.class_id = new.id and q.status = 'pending'
    returning q.*
  loop
    perform private.join_log(r, 'join_declined', jsonb_build_object('reason', r.decline_reason));
  end loop;
  return null;
end;
$$;

create trigger decline_join_requests after update of ended_on on public.classes
  for each row when (new.ended_on is not null and old.ended_on is distinct from new.ended_on)
  execute function private.join_requests_class_ended();

-- -----------------------------------------------------------------------------
-- Demo: four waiting requests and one declined, from demo students who aren't in that class (never guest@ or
-- guest02@: the e2e specs ask from those two). Runs after seed_demo_activity, which replaces the log: it logs its
-- own rows. Re-seeding replaces these students' requests.
-- -----------------------------------------------------------------------------
create function public.seed_demo_class_join_requests()
returns integer
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_now timestamptz := now() - interval '3 minutes';
  v_staff uuid := (select p.id from public.profiles p where p.email = 'staff@demo.oopsdance.test');
  -- who asks for which class, how long ago (hours), and for the declined one when and why
  v_rows jsonb := jsonb_build_array(
    jsonb_build_object('email', 'guest03@demo.oopsdance.test', 'class', 'K-pop Dance', 'start', 'now', 'hours', 3,
      'note', 'Em học Kpop được 6 tháng rồi ạ, muốn vào lớp luôn khoá này.'),
    jsonb_build_object('email', 'guest09@demo.oopsdance.test', 'class', 'Newbie 2', 'start', 'next', 'hours', 7.3,
      'note', 'Em rủ được đứa bạn chưa nhảy bao giờ, cho tụi em vào chung lớp Newbie nha.'),
    jsonb_build_object('email', 'guest08@demo.oopsdance.test', 'class', 'Trending', 'start', 'next', 'hours', 20,
      'note', 'Khoá này lớp học được nửa rồi nên em xin vào từ khoá sau ạ.'),
    jsonb_build_object('email', 'guest07@demo.oopsdance.test', 'class', 'Girlstyle 1', 'start', 'now', 'hours', 30,
      'note', 'Em đang học K-pop, muốn thử thêm Girlstyle. Lần đầu học style này, mong được hướng dẫn từ đầu ạ.'),
    jsonb_build_object('email', 'guest04@demo.oopsdance.test', 'class', 'Choreo CG', 'start', 'now', 'hours', 48,
      'note', 'Em muốn lên lớp nâng cao ạ.', 'decided_hours', 43,
      'reason', 'Lớp Choreo CG đang đủ người. Studio sẽ nhắn bạn khi có chỗ nhé.'));
  v_students uuid[];
  v_count integer;
begin
  if not (private.is_service_context() and public.tuition_sandbox()) then
    raise exception 'FORBIDDEN: demo join requests are only seeded on a sandbox';
  end if;
  select coalesce(array_agg(p.id), '{}') into v_students
    from public.profiles p where p.email in (select x ->> 'email' from jsonb_array_elements(v_rows) x);

  delete from public.activity_log a where a.entity = 'class_join_requests' and a.subject_id = any (v_students);
  delete from public.class_join_requests q where q.student_id = any (v_students);

  -- 'next' only where the class has a next course planned; nobody already in the class.
  insert into public.class_join_requests (class_id, student_id, status, start_pref, note, decided_by, decided_at,
                                          decline_reason, created_at, updated_at)
  select c.id, p.id, (case when d.reason is null then 'pending' else 'declined' end)::public.join_request_status,
         case when d.start = 'next' and exists (select 1 from public.lesson_progress(array[c.id]) lp where lp.status = 'planned')
              then 'next' else 'now' end,
         d.note, case when d.reason is not null then v_staff end, v_now - d.decided_hours * interval '1 hour', d.reason,
         v_now - d.hours * interval '1 hour', v_now - coalesce(d.decided_hours, d.hours) * interval '1 hour'
    from jsonb_to_recordset(v_rows) as d(email text, class text, start text, hours numeric, note text,
                                         decided_hours numeric, reason text)
    join public.profiles p on p.email = d.email
    join public.classes c on c.name = d.class and c.ended_on is null
   where not exists (select 1 from public.class_students cs where cs.class_id = c.id and cs.student_id = p.id);
  get diagnostics v_count = row_count;

  -- Their lines on the Activity page (seed_demo_activity, which runs before, replaces the whole log).
  insert into public.activity_log (at, actor_id, actor_name, actor_role, area, action, entity, entity_id, class_id,
                                   subject_id, label, meta)
  select x.at, x.actor, private.person_name(x.actor), (select p.role from public.profiles p where p.id = x.actor),
         'students', x.action, 'class_join_requests', q.id::text, q.class_id, q.student_id,
         coalesce(private.person_name(q.student_id), ''),
         jsonb_strip_nulls(jsonb_build_object('class', private.class_name(q.class_id)) || x.meta)
    from public.class_join_requests q
   cross join lateral (values
     (q.created_at, q.student_id, 'join_requested', jsonb_build_object('start', q.start_pref, 'note', q.note)),
     (q.decided_at, q.decided_by, 'join_declined', jsonb_build_object('reason', q.decline_reason))) x(at, actor, action, meta)
   where q.student_id = any (v_students) and (x.action = 'join_requested' or q.status = 'declined');

  return v_count;
end;
$$;

