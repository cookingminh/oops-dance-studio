-- "Chính sách huỷ phòng (2026)" → "chinh-sach-huy-phong-2026"; 'article' when nothing is left of the title.
create function private.knowledge_slug(p_title text)
returns text
language sql
immutable
set search_path = ''
as $$
  select coalesce(nullif(btrim(left(btrim(regexp_replace(
           lower(translate(normalize(coalesce(p_title, ''), NFC),
             'àáạảãâầấậẩẫăằắặẳẵÀÁẠẢÃÂẦẤẬẨẪĂẰẮẶẲẴèéẹẻẽêềếệểễÈÉẸẺẼÊỀẾỆỂỄìíịỉĩÌÍỊỈĨòóọỏõôồốộổỗơờớợởỡÒÓỌỎÕÔỒỐỘỔỖƠỜỚỢỞỠùúụủũưừứựửữÙÚỤỦŨƯỪỨỰỬỮỳýỵỷỹỲÝỴỶỸđĐ',
             'aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaeeeeeeeeeeeeeeeeeeeeeeiiiiiiiiiioooooooooooooooooooooooooooooooooouuuuuuuuuuuuuuuuuuuuuuyyyyyyyyyydd')),
           '[^a-z0-9]+', '-', 'g'), '-'), 80), '-'), ''), 'article');
$$;

create function private.knowledge_article_stamp()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_me uuid := auth.uid();
begin
  new.title := btrim(new.title);
  if tg_op = 'INSERT' then
    new.slug := private.knowledge_slug(new.title);
    if exists (select 1 from public.knowledge_articles a where a.slug = new.slug) then
      new.slug := new.slug || '-' || new.id;
    end if;
    new.created_at := now();
    new.updated_at := now();
    -- Without a signed-in person (seed.sql, the SQL editor) the row may name its author itself.
    new.updated_by := coalesce(v_me, case when private.is_service_context() then new.updated_by end);
    new.published_at := case when new.status = 'published' then now() end;
    return new;
  end if;

  new.id := old.id;
  new.slug := old.slug;
  new.created_at := old.created_at;
  new.published_at := case when new.status = 'published' then coalesce(old.published_at, now()) end;
  if (new.title, new.category, new.body, new.status) is distinct from (old.title, old.category, old.body, old.status) then
    new.updated_at := now();
    new.updated_by := coalesce(v_me, case when private.is_service_context() and new.updated_by is distinct from old.updated_by
                                          then new.updated_by end);
  else
    -- Not an edit. updated_by only goes to null (its profile was deleted: on delete set null), so that foreign key
    -- action must go through.
    new.updated_at := old.updated_at;
    new.updated_by := case when new.updated_by is not null then old.updated_by end;
  end if;
  return new;
end;
$$;

create trigger knowledge_article_stamp before insert or update on public.knowledge_articles
  for each row execute function private.knowledge_article_stamp();

-- -----------------------------------------------------------------------------
-- Activity log: area 'settings', label = the title, meta { category, status }; people's actions only.
-- -----------------------------------------------------------------------------
create function private.knowledge_article_log()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_me uuid := auth.uid();
  r public.knowledge_articles := case when tg_op = 'DELETE' then old else new end;
  v_action text;
begin
  if v_me is null or coalesce(current_setting('oops.activity', true), '') = 'off' then
    return null;
  end if;
  v_action := case
    when tg_op = 'INSERT' then 'knowledge_created'
    when tg_op = 'DELETE' then 'knowledge_deleted'
    when new.status <> old.status then case new.status when 'published' then 'knowledge_published' else 'knowledge_unpublished' end
    when (new.title, new.category, new.body) is distinct from (old.title, old.category, old.body) then 'knowledge_updated'
  end;
  if v_action is null then
    return null;
  end if;
  insert into public.activity_log (actor_id, actor_name, actor_role, area, action, entity, entity_id, label, meta)
  values (v_me, private.person_name(v_me), (select p.role from public.profiles p where p.id = v_me),
          'settings', v_action, 'knowledge_articles', r.id::text, r.title,
          jsonb_build_object('category', r.category, 'status', r.status));
  return null;
end;
$$;

create trigger zz_knowledge_article_log after insert or update or delete on public.knowledge_articles
  for each row execute function private.knowledge_article_log();

-- -----------------------------------------------------------------------------
-- RLS: staff and admins (is_staff() is true for both); everyone else gets nothing.
-- -----------------------------------------------------------------------------
alter table public.knowledge_articles enable row level security;
create policy knowledge_articles_select on public.knowledge_articles
  for select to authenticated using ((select public.is_staff()));
create policy knowledge_articles_insert on public.knowledge_articles
  for insert to authenticated with check ((select public.is_staff()));
create policy knowledge_articles_update on public.knowledge_articles
  for update to authenticated using ((select public.is_staff())) with check ((select public.is_staff()));
create policy knowledge_articles_delete on public.knowledge_articles
  for delete to authenticated using ((select public.is_staff()));

-- -----------------------------------------------------------------------------
-- Privileges: the columns people write (the trigger above sets the others).
-- -----------------------------------------------------------------------------
revoke all on public.knowledge_articles from anon, authenticated;
grant select, delete on public.knowledge_articles to authenticated;
grant insert (title, category, body, status), update (title, category, body, status) on public.knowledge_articles to authenticated;

revoke execute on function private.knowledge_slug(text), private.knowledge_article_stamp(), private.knowledge_article_log()
  from public, anon, authenticated;
