-- AI knowledge (api-contract §3 knowledge_articles, §4 RLS).
--
-- Short articles staff write for the studio's future customer-support assistant: policies, FAQ, class guidance, house
-- rules. Published articles will later be synced to a knowledge base; that job isn't designed yet, so nothing but staff
-- and admins reads this table (no public access, no RPC).
--   * category: policy | faq | class | house_rules | other. body: Markdown. status: draft | published.
--   * Staff and admins create, read, change and delete (RLS + table privileges). They write four columns only: title,
--     category, body, status. Everything else is set here, whatever the client sends:
--       slug          from the title when the article is created (accents dropped, "-<id>" added when taken), then
--                     never changed: a stable key for the sync
--       updated_at/by the last change to one of those four columns, and who made it
--       published_at  when it went from draft to published; kept while it stays published; null on a draft
--   * Saving a published article changes the published text at once (one body per article).
--   * Every step is on the Activity page (area 'settings', entity 'knowledge_articles'), never the body.

create table public.knowledge_articles (
  id           bigint generated by default as identity primary key,
  slug         text not null constraint knowledge_articles_slug_key unique
               check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) <= 120),
  title        text not null check (title = btrim(title) and char_length(title) between 1 and 120),
  category     text not null check (category in ('policy', 'faq', 'class', 'house_rules', 'other')),
  body         text not null default '' check (char_length(body) <= 20000),
  status       text not null default 'draft' check (status in ('draft', 'published')),
  updated_by   uuid constraint knowledge_articles_updated_by_fkey references public.profiles (id) on delete set null,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  published_at timestamptz,
  constraint knowledge_articles_published check ((status = 'published') = (published_at is not null)),
  -- a published article says something
  constraint knowledge_articles_published_body check (status = 'draft' or btrim(body, E' \t\r\n') <> '')
);
create index knowledge_articles_updated_by_idx on public.knowledge_articles (updated_by) where updated_by is not null;

