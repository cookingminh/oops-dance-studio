-- A poster file: banners/<name>.<webp|jpg|jpeg|png> in site-assets, already uploaded.
create function private.banner_poster(p_path text, p_which text)
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if p_path is null or p_path !~ '^banners/[A-Za-z0-9_-]{1,80}\.(webp|jpg|jpeg|png)$' then
    raise exception 'INVALID_INPUT: the % poster must be banners/<name>.webp (or .jpg, .png)', p_which;
  end if;
  if not exists (select 1 from storage.objects o where o.bucket_id = 'site-assets' and o.name = p_path) then
    raise exception 'INVALID_INPUT: the % poster % has not been uploaded', p_which, p_path;
  end if;
  return p_path;
end;
$$;

-- One spot on a poster: { x, y } in % (the button's centre), scale 0.6–2.
create function private.banner_spot(p_spot jsonb, p_which text)
returns jsonb
language plpgsql
stable
set search_path = ''
as $$
declare
  v_x numeric;
  v_y numeric;
  v_scale numeric;
begin
  if p_spot is null or jsonb_typeof(p_spot) <> 'object' then
    raise exception 'INVALID_INPUT: every button needs a place on the % poster', p_which;
  end if;
  begin
    v_x := (p_spot ->> 'x')::numeric;
    v_y := (p_spot ->> 'y')::numeric;
    v_scale := coalesce((p_spot ->> 'scale')::numeric, 1);
  exception when others then
    raise exception 'INVALID_INPUT: a button''s place on the % poster is not a number', p_which;
  end;
  if v_x is null or v_y is null or v_x < 0 or v_x > 100 or v_y < 0 or v_y > 100 then
    raise exception 'INVALID_INPUT: a button must sit on the % poster (0–100 %%)', p_which;
  end if;
  if v_scale < 0.6 or v_scale > 2 then
    raise exception 'INVALID_INPUT: a button''s size is between 60 %% and 200 %%';
  end if;
  return jsonb_build_object('x', round(v_x, 2), 'y', round(v_y, 2), 'scale', round(v_scale, 2));
end;
$$;

-- The buttons, checked and reduced to the keys the site reads (a button without an id gets one).
create function private.banner_buttons(p_buttons jsonb)
returns jsonb
language plpgsql
volatile
set search_path = ''
as $$
declare
  v_out jsonb := '[]'::jsonb;
  b jsonb;
  v_vi text;
  v_en text;
  v_link text;
  v_url text;
  v_color text;
begin
  if p_buttons is null then
    return v_out;
  end if;
  if jsonb_typeof(p_buttons) <> 'array' then
    raise exception 'INVALID_INPUT: the buttons are a list';
  end if;
  if jsonb_array_length(p_buttons) > 4 then
    raise exception 'INVALID_INPUT: a banner has up to 4 buttons';
  end if;
  for b in select value from jsonb_array_elements(p_buttons)
  loop
    v_vi := nullif(btrim(b ->> 'text_vi'), '');
    v_en := nullif(btrim(b ->> 'text_en'), '');
    if v_vi is null or char_length(v_vi) > 30 or char_length(coalesce(v_en, '')) > 30 then
      raise exception 'INVALID_INPUT: a button''s text is 1–30 characters';
    end if;
    v_link := b ->> 'link';
    if v_link is null or not (v_link = any (private.banner_link_pages())) then
      raise exception 'INVALID_INPUT: pick where the button leads';
    end if;
    v_url := case when v_link = 'url' then nullif(btrim(b ->> 'url'), '') end;
    if v_link = 'url' and (v_url is null or v_url !~ '^https://[^\s]{3,}$' or char_length(v_url) > 300) then
      raise exception 'INVALID_INPUT: a button''s link starts with https://';
    end if;
    v_color := b ->> 'color';
    if v_color is null or v_color not in ('red', 'white', 'gold', 'dark', 'glass') then
      raise exception 'INVALID_INPUT: a button''s colour is red, white, gold, dark or glass';
    end if;
    v_out := v_out || jsonb_build_array(jsonb_build_object(
      'id', left(coalesce(nullif(b ->> 'id', ''), md5(random()::text)), 40),
      'text_vi', v_vi,
      'text_en', v_en,
      'link', v_link,
      'url', v_url,
      'color', v_color,
      'arrow', coalesce((b ->> 'arrow')::boolean, false),
      'desktop', private.banner_spot(b -> 'desktop', 'desktop'),
      'phone', private.banner_spot(b -> 'phone', 'phone')));
  end loop;
  return v_out;
end;
$$;

create function private.banner_log(p_banner public.home_banners, p_action text, p_meta jsonb default '{}'::jsonb)
returns void
language sql
volatile
security definer
set search_path = ''
as $$
  insert into public.activity_log (actor_id, actor_name, actor_role, area, action, entity, entity_id, label, meta)
  values (auth.uid(), private.person_name(auth.uid()), (select p.role from public.profiles p where p.id = auth.uid()),
          'settings', p_action, 'home_banners', p_banner.id::text, p_banner.name,
          jsonb_build_object('starts_on', p_banner.starts_on, 'ends_on', p_banner.ends_on) || coalesce(p_meta, '{}'::jsonb));
$$;

-- -----------------------------------------------------------------------------
-- Visitors: the banners that show today (the first four, in order).
-- -----------------------------------------------------------------------------
create function public.home_banners_live()
returns table (id bigint, name text, alt_text text, desktop_path text, desktop_width integer, desktop_height integer,
               phone_path text, phone_width integer, phone_height integer, buttons jsonb)
language sql
stable
security definer
set search_path = ''
as $$
  select b.id, b.name, b.alt_text, b.desktop_path, b.desktop_width, b.desktop_height,
         b.phone_path, b.phone_width, b.phone_height, b.buttons
    from public.home_banners b
   where b.enabled
     and (b.starts_on is null or b.starts_on <= public.studio_today())
     and (b.ends_on is null or b.ends_on >= public.studio_today())
   order by b.sort_order, b.id
   limit 4;
$$;

