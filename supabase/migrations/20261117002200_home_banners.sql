-- Homepage banners (api-contract §3 home_banners, §5 Homepage banners).
--
-- The homepage hero becomes a carousel: the studio's own slide (the video) first, then up to four banners staff
-- post from /admin/banners. A banner is a poster designed elsewhere (Canva…), in two versions:
--   * desktop: landscape 16:9, 1920 × 1080; phone: portrait 9:16, 1080 × 1920 — both required.
--   * the site always shows the whole poster (never cropped) and fills the rest of the screen with a blurred copy,
--     so a button placed at x %, y % of the poster stays on that spot of the design on every screen.
--   * buttons (0–4) are laid over the poster: text in Vietnamese (and English, optional), where they lead (a page of
--     the site or an https link), a colour, an arrow, and per device a position (x, y: % of the poster, the button's
--     centre) and a scale (0.6–2: its size relative to the standard button).
--   * starts_on / ends_on (studio dates, inclusive; null = no limit) and enabled decide when it shows; sort_order
--     the order. home_banners_live() gives visitors the first four that show today.
-- Staff and admins read the table and write through the RPCs (logged on the Activity page, area 'settings').
-- Posters live in the public bucket site-assets under banners/; the RPCs hand back the files nothing uses any more,
-- for the app to delete through the Storage API.

create table public.home_banners (
  id             bigint generated by default as identity primary key,
  name           text not null check (char_length(name) between 1 and 60),
  alt_text       text not null check (char_length(alt_text) between 1 and 400),
  desktop_path   text not null,
  desktop_width  integer not null check (desktop_width > 0),
  desktop_height integer not null check (desktop_height > 0),
  phone_path     text not null,
  phone_width    integer not null check (phone_width > 0),
  phone_height   integer not null check (phone_height > 0),
  starts_on      date,
  ends_on        date,
  enabled        boolean not null default true,
  sort_order     integer not null default 0,
  buttons        jsonb not null default '[]'::jsonb check (jsonb_typeof(buttons) = 'array' and jsonb_array_length(buttons) <= 4),
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  created_by     uuid references public.profiles (id) on delete set null,
  updated_by     uuid references public.profiles (id) on delete set null,
  constraint home_banners_dates check (ends_on is null or starts_on is null or ends_on >= starts_on)
);
create index home_banners_order_idx on public.home_banners (sort_order, id);

alter table public.home_banners enable row level security;
create policy home_banners_staff_read on public.home_banners for select to authenticated using (public.is_staff());
revoke all on public.home_banners from anon;
revoke insert, update, delete, truncate, references, trigger on public.home_banners from authenticated;
grant select on public.home_banners to authenticated;

