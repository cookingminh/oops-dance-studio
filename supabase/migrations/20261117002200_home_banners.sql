-- Create (p_id null) or change a banner. p_banner: { name, alt_text, desktop_path, desktop_width, desktop_height,
-- phone_path, phone_width, phone_height, starts_on, ends_on, enabled, buttons }.
-- → { banner: the row, unused_paths: posters it no longer uses (to delete from Storage) }
create function public.home_banner_save(p_id bigint, p_banner jsonb)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_old public.home_banners;
  b public.home_banners;
  v_name text := nullif(btrim(p_banner ->> 'name'), '');
  v_alt text := nullif(btrim(p_banner ->> 'alt_text'), '');
  v_starts date;
  v_ends date;
  v_unused text[] := '{}'::text[];
begin
  if not (public.is_staff() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only admins and staff change the homepage banners';
  end if;
  if p_banner is null or jsonb_typeof(p_banner) <> 'object' then
    raise exception 'INVALID_INPUT: the banner is missing';
  end if;
  if v_name is null or char_length(v_name) > 60 then
    raise exception 'INVALID_INPUT: give the banner a name (up to 60 characters)';
  end if;
  if v_alt is null or char_length(v_alt) > 400 then
    raise exception 'INVALID_INPUT: write what the poster says (up to 400 characters)';
  end if;
  begin
    v_starts := nullif(p_banner ->> 'starts_on', '')::date;
    v_ends := nullif(p_banner ->> 'ends_on', '')::date;
  exception when others then
    raise exception 'INVALID_INPUT: the dates are not valid';
  end;
  if v_starts is not null and v_ends is not null and v_ends < v_starts then
    raise exception 'INVALID_INPUT: the banner ends before it starts';
  end if;

  if coalesce((p_banner ->> 'desktop_width')::integer, 0) <= 0 or coalesce((p_banner ->> 'desktop_height')::integer, 0) <= 0
     or coalesce((p_banner ->> 'phone_width')::integer, 0) <= 0 or coalesce((p_banner ->> 'phone_height')::integer, 0) <= 0 then
    raise exception 'INVALID_INPUT: both posters are needed, with their size';
  end if;

  if p_id is not null then
    select * into v_old from public.home_banners where id = p_id for update;
    if not found then
      raise exception 'NOT_FOUND: no such banner';
    end if;
  end if;

  if p_id is null then
    insert into public.home_banners (name, alt_text, desktop_path, desktop_width, desktop_height, phone_path, phone_width,
                                     phone_height, starts_on, ends_on, enabled, sort_order, buttons, created_by, updated_by)
    values (v_name, v_alt,
            private.banner_poster(p_banner ->> 'desktop_path', 'desktop'), (p_banner ->> 'desktop_width')::integer,
            (p_banner ->> 'desktop_height')::integer,
            private.banner_poster(p_banner ->> 'phone_path', 'phone'), (p_banner ->> 'phone_width')::integer,
            (p_banner ->> 'phone_height')::integer,
            v_starts, v_ends, coalesce((p_banner ->> 'enabled')::boolean, true),
            coalesce((select max(x.sort_order) + 1 from public.home_banners x), 0),
            private.banner_buttons(p_banner -> 'buttons'), auth.uid(), auth.uid())
    returning * into b;
    perform private.banner_log(b, 'banner_created');
  else
    update public.home_banners
       set name = v_name, alt_text = v_alt,
           desktop_path = private.banner_poster(p_banner ->> 'desktop_path', 'desktop'),
           desktop_width = (p_banner ->> 'desktop_width')::integer, desktop_height = (p_banner ->> 'desktop_height')::integer,
           phone_path = private.banner_poster(p_banner ->> 'phone_path', 'phone'),
           phone_width = (p_banner ->> 'phone_width')::integer, phone_height = (p_banner ->> 'phone_height')::integer,
           starts_on = v_starts, ends_on = v_ends, enabled = coalesce((p_banner ->> 'enabled')::boolean, v_old.enabled),
           buttons = private.banner_buttons(p_banner -> 'buttons'), updated_at = now(), updated_by = auth.uid()
     where id = p_id
    returning * into b;
    if v_old.desktop_path <> b.desktop_path then v_unused := v_unused || v_old.desktop_path; end if;
    if v_old.phone_path <> b.phone_path then v_unused := v_unused || v_old.phone_path; end if;
    perform private.banner_log(b, 'banner_updated', jsonb_build_object('posters_changed', cardinality(v_unused)));
  end if;
  return jsonb_build_object('banner', to_jsonb(b), 'unused_paths', to_jsonb(v_unused));
end;
$$;

-- Show or hide a banner without touching it otherwise → the row.
create function public.home_banner_set_enabled(p_id bigint, p_enabled boolean)
returns public.home_banners
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  b public.home_banners;
begin
  if not (public.is_staff() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only admins and staff change the homepage banners';
  end if;
  if p_enabled is null then
    raise exception 'INVALID_INPUT: say whether the banner shows';
  end if;
  select * into b from public.home_banners where id = p_id for update;
  if not found then
    raise exception 'NOT_FOUND: no such banner';
  end if;
  if b.enabled = p_enabled then
    return b;
  end if;
  update public.home_banners set enabled = p_enabled, updated_at = now(), updated_by = auth.uid() where id = p_id returning * into b;
  perform private.banner_log(b, case when p_enabled then 'banner_shown' else 'banner_hidden' end);
  return b;
end;
$$;

-- Put the banners in this order (the ids given first, in that order; the others keep theirs after them).
create function public.home_banners_reorder(p_ids bigint[])
returns void
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_count integer;
begin
  if not (public.is_staff() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only admins and staff change the homepage banners';
  end if;
  if p_ids is null or cardinality(p_ids) = 0 then
    raise exception 'INVALID_INPUT: give the banners in their new order';
  end if;
  update public.home_banners b set sort_order = x.ord - 1, updated_at = now(), updated_by = auth.uid()
    from unnest(p_ids) with ordinality as x(id, ord)
   where b.id = x.id;
  get diagnostics v_count = row_count;
  if v_count = 0 then
    raise exception 'NOT_FOUND: no such banners';
  end if;
  update public.home_banners b set sort_order = cardinality(p_ids) + b.sort_order
   where not (b.id = any (p_ids));
  insert into public.activity_log (actor_id, actor_name, actor_role, area, action, entity, label, meta)
  values (auth.uid(), private.person_name(auth.uid()), (select p.role from public.profiles p where p.id = auth.uid()),
          'settings', 'banners_reordered', 'home_banners', 'Homepage banners',
          jsonb_build_object('order', (select jsonb_agg(b.name order by x.ord) from unnest(p_ids) with ordinality x(id, ord)
                                       join public.home_banners b on b.id = x.id)));
end;
$$;

-- Delete a banner → its posters' paths (to delete from Storage).
create function public.home_banner_delete(p_id bigint)
returns text[]
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  b public.home_banners;
begin
  if not (public.is_staff() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only admins and staff change the homepage banners';
  end if;
  delete from public.home_banners where id = p_id returning * into b;
  if not found then
    raise exception 'NOT_FOUND: no such banner';
  end if;
  perform private.banner_log(b, 'banner_deleted');
  return array[b.desktop_path, b.phone_path];
end;
$$;

