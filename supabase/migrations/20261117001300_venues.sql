-- Rented studios (venues): while the studio's own rooms are closed, classes are taught in studios rented by
-- the hour elsewhere ("Studio Baladi Vũ Thạnh", "Studio Thỏ"…). The two rooms and everything about them stay
-- as they are (room bookings, clashes, prices), for when the studio reopens.
--
--   * venues: name, address, map link, rent per hour (staff only), active.
--   * A class is taught in one place: one of the rooms (classes.room_id) or a venue (classes.venue_id), never
--     both. Its sessions carry the same place (instructor_attendance.room_id / venue_id): new sessions take
--     the class's place, and moving the class moves its sessions not started yet.
--   * The rent is a cost: once a session at a venue has ended (not called off), it becomes an expense
--     (category 'venue_rent', rent per hour × the session's length, rounded to 1,000 ₫, on the class),
--     so the finance report and the class's money count it. Daily job + venue_rent_run() on demand.
--     Calling a session off afterwards removes its rent; an admin who deletes a session's rent (the studio
--     didn't charge for it) is remembered, so it isn't charged again.
--   * The public timetable and the session-changes feed name the place (room or venue), with its kind and the
--     venue's address and map link on the timetable.

-- ---------------------------------------------------------------------------
-- Venues
-- ---------------------------------------------------------------------------
create table public.venues (
  id            bigint generated by default as identity primary key,
  name          text not null unique check (char_length(btrim(name)) between 1 and 100),
  address       text check (char_length(address) <= 200),
  map_url       text check (map_url ~ '^https://' and char_length(map_url) <= 500),
  rent_per_hour numeric(12,0) not null default 0 check (rent_per_hour >= 0),
  note          text check (char_length(note) <= 300),
  active        boolean not null default true,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create trigger set_updated_at before update on public.venues
  for each row execute function private.set_updated_at();

-- Everyone may see where classes are taught; the rent and the note are staff's (venues_list()).
alter table public.venues enable row level security;
create policy venues_select on public.venues for select to anon, authenticated using (true);
revoke all on public.venues from anon, authenticated;
grant select (id, name, address, map_url, active, created_at, updated_at) on public.venues to anon, authenticated;

-- ---------------------------------------------------------------------------
-- Where a class and its sessions are taught
-- ---------------------------------------------------------------------------
alter table public.classes
  add column venue_id bigint references public.venues (id) on delete set null,
  add constraint classes_one_place check (room_id is null or venue_id is null);
create index classes_venue_id_idx on public.classes (venue_id);

alter table public.instructor_attendance
  add column venue_id bigint references public.venues (id) on delete set null,
  add constraint instructor_attendance_one_place check (room_id is null or venue_id is null);
create index instructor_attendance_venue_idx on public.instructor_attendance (venue_id) where venue_id is not null;

-- A new session without a place takes its class's venue (the room is copied by whoever inserts it).
create function private.session_place()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.room_id is null and new.venue_id is null then
    select c.venue_id into new.venue_id from public.classes c where c.id = new.class_id;
  end if;
  return new;
end;
$$;

create trigger session_place before insert on public.instructor_attendance
  for each row execute function private.session_place();

-- The class moved (to a room, to a venue, or to no place): its sessions not started yet follow.
create function private.class_place_changed()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_logging text := coalesce(current_setting('oops.activity', true), '');
begin
  perform set_config('oops.activity', 'off', true);
  update public.instructor_attendance a
     set room_id = new.room_id, venue_id = new.venue_id
   where a.class_id = new.id
     and a.status = 'pending'
     and a.checkin_at is null
     and a.date >= public.studio_today();
  perform set_config('oops.activity', v_logging, true);
  return null;
end;
$$;

create trigger class_place_changed after update of room_id, venue_id on public.classes
  for each row when (old.room_id is distinct from new.room_id or old.venue_id is distinct from new.venue_id)
  execute function private.class_place_changed();

