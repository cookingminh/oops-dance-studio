-- Add (p_id null) or change a venue → the venue. Logged in the activity log (area 'rooms').
create function public.venue_save(
  p_id      bigint,
  p_name    text,
  p_address text default null,
  p_map_url text default null,
  p_rent    numeric default 0,
  p_note    text default null,
  p_active  boolean default true
)
returns public.venues
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v public.venues;
  o public.venues;
  v_name text := btrim(coalesce(p_name, ''));
  v_map text := nullif(btrim(coalesce(p_map_url, '')), '');
begin
  if not (public.is_staff() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only staff can manage rented studios';
  end if;
  if v_name = '' or char_length(v_name) > 100 then
    raise exception 'INVALID_INPUT: give the studio a name (up to 100 characters)';
  end if;
  if p_rent is null or p_rent < 0 then
    raise exception 'INVALID_INPUT: the rent must be 0 or more';
  end if;
  if v_map is not null and v_map !~ '^https://' then
    raise exception 'INVALID_INPUT: the map link must start with https://';
  end if;
  if exists (select 1 from public.venues x where lower(x.name) = lower(v_name) and x.id is distinct from p_id) then
    raise exception 'INVALID_INPUT: there is already a studio called %', v_name;
  end if;

  if p_id is null then
    insert into public.venues (name, address, map_url, rent_per_hour, note, active)
    values (v_name, nullif(left(btrim(coalesce(p_address, '')), 200), ''), v_map, round(p_rent),
            nullif(left(btrim(coalesce(p_note, '')), 300), ''), coalesce(p_active, true))
    returning * into v;
  else
    select * into o from public.venues where id = p_id for update;
    if not found then
      raise exception 'NOT_FOUND: no such studio';
    end if;
    update public.venues
       set name = v_name,
           address = nullif(left(btrim(coalesce(p_address, '')), 200), ''),
           map_url = v_map,
           rent_per_hour = round(p_rent),
           note = nullif(left(btrim(coalesce(p_note, '')), 300), ''),
           active = coalesce(p_active, true)
     where id = p_id
    returning * into v;
  end if;

  insert into public.activity_log (actor_id, actor_name, actor_role, area, action, entity, entity_id, label, changes, meta)
  select auth.uid(), private.person_name(auth.uid()), (select p.role from public.profiles p where p.id = auth.uid()),
         'rooms', case when o.id is null then 'venue_added' else 'venue_changed' end, 'venues', v.id::text, v.name,
         case when o.id is null then null else (
           select nullif(jsonb_object_agg(k, jsonb_build_object('from', to_jsonb(o) -> k, 'to', to_jsonb(v) -> k)), '{}'::jsonb)
             from unnest(array['name', 'address', 'map_url', 'rent_per_hour', 'active']) k
            where to_jsonb(o) -> k is distinct from to_jsonb(v) -> k) end,
         jsonb_build_object('rent', v.rent_per_hour, 'address', v.address, 'active', v.active);
  return v;
end;
$$;

-- Remove a venue nobody ever used; one that taught classes can only be set inactive.
create function public.venue_delete(p_id bigint)
returns void
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v public.venues;
begin
  if not (public.is_staff() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only staff can manage rented studios';
  end if;
  select * into v from public.venues where id = p_id for update;
  if not found then
    raise exception 'NOT_FOUND: no such studio';
  end if;
  if exists (select 1 from public.classes c where c.venue_id = p_id)
     or exists (select 1 from public.instructor_attendance a where a.venue_id = p_id) then
    raise exception 'INVALID_STATE: classes were taught there: set it inactive instead';
  end if;
  delete from public.venues where id = p_id;
  insert into public.activity_log (actor_id, actor_name, actor_role, area, action, entity, entity_id, label)
  select auth.uid(), private.person_name(auth.uid()), (select p.role from public.profiles p where p.id = auth.uid()),
         'rooms', 'venue_removed', 'venues', v.id::text, v.name;
end;
$$;

