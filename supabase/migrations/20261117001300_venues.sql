create unique index expenses_session_once on public.expenses (session_id) where session_id is not null;

-- Sessions whose rent an admin deleted (the studio didn't charge for it): never charged again.
create table private.venue_rent_skips (
  session_id bigint primary key references public.instructor_attendance (id) on delete cascade,
  skipped_by uuid,
  skipped_at timestamptz not null default now()
);

create function private.venue_rent_deleted()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  -- A session called off loses its rent by itself (session_rent_refunded); only a deleted rent of a session
  -- that still stands is remembered.
  if old.category = 'venue_rent' and old.session_id is not null
     and exists (select 1 from public.instructor_attendance a where a.id = old.session_id and a.status <> 'cancelled') then
    insert into private.venue_rent_skips (session_id, skipped_by) values (old.session_id, auth.uid())
    on conflict do nothing;
  end if;
  return null;
end;
$$;

create trigger venue_rent_deleted after delete on public.expenses
  for each row execute function private.venue_rent_deleted();

-- Charge one session's rent: a session at a venue that has ended and wasn't called off, once. → the expense id
-- (null when nothing was charged). The expense is the system's (created_by null), not logged.
create function private.charge_venue_rent(a public.instructor_attendance)
returns bigint
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v public.venues;
  w record;
  v_class text;
  v_amount numeric;
  v_id bigint;
  v_logging text := coalesce(current_setting('oops.activity', true), '');
begin
  if a.venue_id is null or a.status = 'cancelled'
     or exists (select 1 from private.venue_rent_skips k where k.session_id = a.id) then
    return null;
  end if;
  select * into v from public.venues where id = a.venue_id;
  if not found or v.rent_per_hour <= 0 then
    return null;
  end if;
  select * into w from private.session_window(a);
  if w.starts_at is null or w.ends_at is null or w.ends_at > now() then
    return null;
  end if;
  v_amount := round(v.rent_per_hour * extract(epoch from (w.ends_at - w.starts_at)) / 3600 / 1000) * 1000;
  if v_amount <= 0 then
    return null;
  end if;
  select c.name into v_class from public.classes c where c.id = a.class_id;

  perform set_config('oops.activity', 'off', true);
  insert into public.expenses (spent_on, category, amount, description, vendor, class_id, session_id, created_by)
  values (a.date, 'venue_rent', v_amount,
          left(format('Studio rent: %s, %s–%s', coalesce(v_class, 'class'),
                      to_char(w.starts_at at time zone 'Asia/Ho_Chi_Minh', 'HH24:MI'),
                      to_char(w.ends_at at time zone 'Asia/Ho_Chi_Minh', 'HH24:MI')), 200),
          v.name, a.class_id, a.id, null)
  on conflict (session_id) where session_id is not null do nothing
  returning id into v_id;
  perform set_config('oops.activity', v_logging, true);
  return v_id;
end;
$$;

-- Charge every ended session at a venue of the last 60 days that has no rent yet → how many were charged.
-- The daily job runs it; staff can run it any time (a session that ended an hour ago is charged then).
create function public.venue_rent_run()
returns integer
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  a public.instructor_attendance;
  v_count integer := 0;
begin
  if not (public.is_staff() or private.is_service_context()) then
    raise exception 'FORBIDDEN: staff only';
  end if;
  for a in
    select x.* from public.instructor_attendance x
     where x.venue_id is not null
       and x.status <> 'cancelled'
       and x.date between public.studio_today() - 60 and public.studio_today()
       and not exists (select 1 from public.expenses e where e.session_id = x.id)
       and not exists (select 1 from private.venue_rent_skips k where k.session_id = x.id)
     order by x.date, x.id
  loop
    if private.charge_venue_rent(a) is not null then
      v_count := v_count + 1;
    end if;
  end loop;
  return v_count;
end;
$$;

-- A session called off after its rent was charged: the rent goes (only the automatic expense).
create function private.session_rent_refunded()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  delete from public.expenses e where e.session_id = new.id and e.category = 'venue_rent' and e.created_by is null;
  return null;
end;
$$;

create trigger session_rent_refunded after update of status on public.instructor_attendance
  for each row when (new.status = 'cancelled' and old.status is distinct from new.status)
  execute function private.session_rent_refunded();

select cron.schedule('venue-rent', '20 17 * * *', $$select public.venue_rent_run()$$);

-- ---------------------------------------------------------------------------
-- Naming the place: the public timetable and the session-changes feed
-- ---------------------------------------------------------------------------
-- room_name is the place's name (a room or a venue), place_kind which ('room' | 'venue' | null); a venue adds
-- its address and map link.
drop function public.list_public_classes();
create function public.list_public_classes()
returns table (id bigint, name text, price numeric, lesson text, image_path text, room_name text, instructor_name text,
               instructor_avatar_path text, schedules jsonb, venue_address text, venue_map_url text, place_kind text)
language sql
stable
security definer
set search_path = ''
as $$
  select c.id,
         c.name,
         c.price,
         c.lesson,
         c.image_path,
         coalesce(r.name, v.name),
         p.full_name,
         p.avatar_path,
         coalesce(
           (select jsonb_agg(
                     jsonb_build_object(
                       'day_of_week', s.day_of_week,
                       'start_time',  s.start_time,
                       'end_time',    s.end_time)
                     order by s.day_of_week, s.start_time)
            from public.class_schedules s
            where s.class_id = c.id),
           '[]'::jsonb),
         v.address,
         v.map_url,
         case when r.id is not null then 'room' when v.id is not null then 'venue' end
  from public.classes c
  join public.profiles p on p.id = c.instructor_id
  left join public.rooms r on r.id = c.room_id
  left join public.venues v on v.id = c.venue_id
  where c.ended_on is null or c.ended_on >= public.studio_today()
  order by c.name;
$$;
grant execute on function public.list_public_classes() to anon, authenticated;

create or replace function public.my_session_changes(p_days integer default 21)
returns table (id bigint, class_id bigint, class_name text, date date, kind text, start_time time, end_time time,
               reason text, makes_up date, room_name text)
language sql
stable
security definer
set search_path = ''
as $$
  select a.id, a.class_id, c.name, a.date,
         case when a.status = 'cancelled' then 'cancelled' else 'make_up' end,
         coalesce(a.start_time, (select min(s.start_time) from public.class_schedules s
                                  where s.class_id = a.class_id and s.day_of_week = extract(isodow from a.date))),
         coalesce(a.end_time, (select max(s.end_time) from public.class_schedules s
                                where s.class_id = a.class_id and s.day_of_week = extract(isodow from a.date))),
         case when a.status = 'cancelled' then a.cancel_reason
              else (select o.cancel_reason from public.instructor_attendance o
                     where o.class_id = a.class_id and o.date = a.makes_up and o.status = 'cancelled') end,
         a.makes_up,
         coalesce((select r.name from public.rooms r where r.id = coalesce(a.room_id, c.room_id)),
                  (select v.name from public.venues v where v.id = coalesce(a.venue_id, c.venue_id)))
    from public.instructor_attendance a
    join public.classes c on c.id = a.class_id
   where a.date between public.studio_today() and public.studio_today() + least(greatest(coalesce(p_days, 21), 1), 90)
     and (a.status = 'cancelled' or (a.is_extra and a.status <> 'cancelled'))
     and (a.instructor_id = auth.uid() or c.instructor_id = auth.uid()
          or exists (select 1 from public.class_students cs
                      where cs.class_id = a.class_id and cs.student_id = auth.uid() and cs.joined_at <= a.date
                        and (cs.leaves_after is null or cs.leaves_after >= a.date)))
   order by a.date, 6;
$$;

-- ---------------------------------------------------------------------------
-- Demo: the studio's rooms are closed; its classes are taught in two rented studios
-- ---------------------------------------------------------------------------
-- Adds the two studios (example rents), moves the demo classes there with their sessions, stops the old
-- premises' monthly rent from the month the classes moved, and charges the rent of the sessions already
-- taught. Safe to run again.
create function public.seed_demo_venues()
returns void
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_baladi bigint;
  v_tho bigint;
  v_moved date;
  s public.instructor_attendance;
  v_logging text := coalesce(current_setting('oops.activity', true), '');
begin
  insert into public.venues (name, address, rent_per_hour, note)
  values ('Studio Baladi Vũ Thạnh', 'Vũ Thạnh, Ô Chợ Dừa, Đống Đa, Hà Nội', 250000, 'Example rent: change it to the real price.'),
         ('Studio Thỏ', null, 200000, 'Example rent: change it to the real price.')
  on conflict (name) do nothing;
  select id into v_baladi from public.venues where name = 'Studio Baladi Vũ Thạnh';
  select id into v_tho from public.venues where name = 'Studio Thỏ';

  perform set_config('oops.activity', 'off', true);
  -- The classes still running (an ended one stays in the room it had). No two at the same venue at once.
  update public.classes c
     set venue_id = case when c.name in ('K-pop Cover Cơ Bản', 'K-pop Cover Nâng Cao', 'Waacking Basics') then v_baladi else v_tho end,
         room_id = null
   where c.ended_on is null
     and c.name in ('K-pop Cover Cơ Bản', 'K-pop Cover Nâng Cao', 'Waacking Basics', 'Hip-hop Foundation', 'Breaking Kids',
                    'Contemporary & Jazz', 'Choreography Sáng Tạo');
  -- Every session of those classes, taught or not, was at its venue.
  update public.instructor_attendance a
     set venue_id = c.venue_id, room_id = null
    from public.classes c
   where c.id = a.class_id and c.venue_id is not null and (a.venue_id is distinct from c.venue_id or a.room_id is not null);

  -- The premises closed when the classes moved out: its monthly rent stops from that month.
  select date_trunc('month', min(x.date))::date into v_moved
    from public.instructor_attendance x join public.classes c on c.id = x.class_id
   where x.venue_id is not null and c.ended_on is null;
  if v_moved is not null then
    update public.recurring_expenses r
       set ends_on = greatest((v_moved - interval '1 month')::date, r.starts_on), active = false  -- the last month it ran
     where r.category = 'rent' and (r.ends_on is null or r.ends_on >= v_moved);
    delete from public.expenses e where e.category = 'rent' and e.recurring_id is not null and e.month >= v_moved;
  end if;
  perform set_config('oops.activity', v_logging, true);

  for s in
    select x.* from public.instructor_attendance x
     where x.venue_id is not null and x.status <> 'cancelled' and x.date <= public.studio_today()
       and not exists (select 1 from public.expenses e where e.session_id = x.id)
  loop
    perform private.charge_venue_rent(s);
  end loop;
end;
$$;

