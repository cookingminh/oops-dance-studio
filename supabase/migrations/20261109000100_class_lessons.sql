-- -----------------------------------------------------------------------------
-- class_lessons: the piece (song) a class learns each month.
--   * one row per (class, month); `month` is the first day of that month
--   * classes.lesson mirrors the title of the latest month, so the homepage RPC and
--     the profile pages keep reading one column
--   * a class with no row for the current month keeps showing the latest one; the
--     admin UI flags it as "needs this month's lesson"
-- Public read (like classes), staff write.
-- -----------------------------------------------------------------------------
create table public.class_lessons (
  id         bigint generated by default as identity primary key,
  class_id   bigint not null references public.classes (id) on delete cascade,
  month      date not null check (month = date_trunc('month', month)::date),
  title      text not null check (char_length(btrim(title)) between 1 and 120),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (class_id, month)
);

create trigger set_updated_at before update on public.class_lessons
  for each row execute function private.set_updated_at();

-- Keep classes.lesson = title of the class's latest month (null when it has none).
create or replace function private.sync_class_lesson()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op <> 'INSERT' then
    update public.classes c
       set lesson = (select l.title from public.class_lessons l
                      where l.class_id = old.class_id order by l.month desc limit 1)
     where c.id = old.class_id;
  end if;
  if tg_op <> 'DELETE' then
    update public.classes c
       set lesson = (select l.title from public.class_lessons l
                      where l.class_id = new.class_id order by l.month desc limit 1)
     where c.id = new.class_id;
  end if;
  return null;
end;
$$;

create trigger sync_class_lesson
  after insert or update or delete on public.class_lessons
  for each row execute function private.sync_class_lesson();

revoke execute on function private.sync_class_lesson() from public, anon, authenticated;

alter table public.class_lessons enable row level security;

create policy class_lessons_select on public.class_lessons
  for select to anon, authenticated using (true);
create policy class_lessons_insert on public.class_lessons
  for insert to authenticated with check ((select public.is_staff()));
create policy class_lessons_update on public.class_lessons
  for update to authenticated using ((select public.is_staff())) with check ((select public.is_staff()));
create policy class_lessons_delete on public.class_lessons
  for delete to authenticated using ((select public.is_staff()));

revoke truncate, references, trigger on public.class_lessons from anon, authenticated;
revoke insert, update, delete on public.class_lessons from anon;

-- Existing lessons become the lesson of the month the class was created in (studio time).
insert into public.class_lessons (class_id, month, title)
select c.id,
       date_trunc('month', c.created_at at time zone 'Asia/Ho_Chi_Minh')::date,
       left(btrim(c.lesson), 120)
  from public.classes c
 where nullif(btrim(c.lesson), '') is not null
on conflict (class_id, month) do nothing;
