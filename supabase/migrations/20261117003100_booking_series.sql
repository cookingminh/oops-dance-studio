-- Recurring room rentals, paid by month — api-contract §3 booking_series, booking_series_bills, bookings.series_id,
-- bank_transfers.series_id / series_month; §5 booking_series_preview, booking_series_create, booking_series_summary,
-- booking_series_record_payment, booking_series_simulate_transfer, booking_series_cancel_rest
--
-- A regular renter (a crew rehearsing every Tuesday evening, say) is booked once for weeks ahead, by staff:
--   * staff pick who (an account or a walk-in), the room, the weekdays, the times and the dates from … to;
--     booking_series_preview lists every day with what already holds the room then (a booking, a class) and the
--     rooms still free, and for each clashing day staff decide: skip it, another room, or other times;
--   * booking_series_create books the days kept, one ordinary booking each (approved, or held), at the room's price
--     less the series discount — a percentage, or an amount off each session — with its reason (each booking keeps
--     its list price and the reason as its price note, like any changed price);
--   * the renter pays by month: one payment code per month of the series (booking_series_bills). A transfer with
--     that code pays the month's sessions in date order (private.match_transfer); staff record cash or a transfer
--     seen by hand for a month the same way (booking_series_record_payment); the demo can simulate one;
--   * booking_series_summary: the series, and per month its sessions, total, paid, balance and code;
--     booking_series_cancel_rest cancels its sessions still ahead (each with the cancellation policy).
-- The sessions stay ordinary bookings: the calendar, the list, payments by booking, refunds and reports see them.

-- -----------------------------------------------------------------------------
-- Tables
-- -----------------------------------------------------------------------------
create table public.booking_series (
  id             bigint generated by default as identity primary key,
  guest_id       uuid references public.profiles (id),
  walk_in_name   text check (char_length(btrim(walk_in_name)) between 1 and 80),
  walk_in_phone  text check (walk_in_phone ~ '^[0-9+ .()-]{6,20}$'),
  room_id        bigint not null references public.rooms (id),
  weekdays       smallint[] not null check (cardinality(weekdays) between 1 and 7 and weekdays <@ array[1, 2, 3, 4, 5, 6, 7]::smallint[]),
  start_time     time not null,
  end_time       time not null,
  starts_on      date not null,
  ends_on        date not null,
  discount_kind  text check (discount_kind in ('percent', 'amount')),
  discount_value numeric(12, 0) check (discount_value > 0),
  discount_note  text check (char_length(discount_note) <= 300),
  details        text check (char_length(details) <= 1000),
  created_by     uuid references public.profiles (id) on delete set null default auth.uid(),
  created_at     timestamptz not null default now(),
  constraint booking_series_who check ((guest_id is null) = (walk_in_name is not null)),
  constraint booking_series_times check (end_time > start_time),
  constraint booking_series_dates check (ends_on >= starts_on and ends_on <= starts_on + 366),
  constraint booking_series_discount check ((discount_kind is null) = (discount_value is null)
                                            and (discount_kind is distinct from 'percent' or discount_value < 100))
);
comment on table public.booking_series is
  'A recurring rental: the same room, weekdays and times from starts_on to ends_on, booked by staff as one booking per day (bookings.series_id), paid by month (booking_series_bills).';
create index booking_series_guest_idx on public.booking_series (guest_id);

alter table public.bookings add column series_id bigint references public.booking_series (id) on delete set null;
create index bookings_series_idx on public.bookings (series_id) where series_id is not null;
comment on column public.bookings.series_id is 'The recurring rental this booking is one session of (booking_series), or null.';

-- One payment code per month of a series: a transfer with it pays that month's sessions.
create table public.booking_series_bills (
  series_id    bigint not null references public.booking_series (id) on delete cascade,
  month        date not null check (extract(day from month) = 1),
  payment_code text not null unique check (payment_code ~ '^OOPS[2-9A-HJ-NP-Z]{6}$'),
  primary key (series_id, month)
);

alter table public.bank_transfers
  add column series_id    bigint references public.booking_series (id) on delete set null,
  add column series_month date;
comment on column public.bank_transfers.series_id is 'A transfer that paid a month of a recurring rental (with series_month).';

alter table public.booking_series enable row level security;
alter table public.booking_series_bills enable row level security;
create policy booking_series_select on public.booking_series for select to authenticated
  using (guest_id = (select auth.uid()) or (select public.is_staff()));
create policy booking_series_bills_select on public.booking_series_bills for select to authenticated
  using ((select public.is_staff())
         or exists (select 1 from public.booking_series s where s.id = series_id and s.guest_id = (select auth.uid())));
grant select on public.booking_series, public.booking_series_bills to authenticated;

-- One code space for invoices, bookings and the months of recurring rentals.
create or replace function private.new_payment_code()
returns text
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_chars constant text := '23456789ABCDEFGHJKLMNPQRSTUVWXYZ';
  v_code text;
begin
  loop
    v_code := 'OOPS' || (select string_agg(substr(v_chars, 1 + floor(random() * 32)::int, 1), '')
                           from generate_series(1, 6));
    exit when not exists (select 1 from public.tuition_invoices i where i.payment_code = v_code)
          and not exists (select 1 from public.bookings b where b.payment_code = v_code)
          and not exists (select 1 from public.booking_series_bills x where x.payment_code = v_code);
  end loop;
  return v_code;
end;
$$;

