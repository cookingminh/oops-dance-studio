-- The series' sessions in a month that still count (waiting, approved, paid up), in date order.
create function private.series_month_bookings(p_series bigint, p_month date)
returns setof public.bookings
language sql
stable
security definer
set search_path = ''
as $$
  select * from public.bookings b
   where b.series_id = p_series and date_trunc('month', b.date)::date = p_month
     and b.status in ('pending', 'approved', 'completed')
   order by b.date, b.start_time, b.id;
$$;

-- What a month of a series still owes (its live sessions' agreed prices less what they received).
create function private.series_month_balance(p_series bigint, p_month date)
returns numeric
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(sum(greatest(coalesce(b.full_payment, 0) - coalesce(b.bank_transfer, 0) - coalesce(b.cash, 0), 0)), 0)
    from private.series_month_bookings(p_series, p_month) b;
$$;

-- Money for a month of a series, spread over its sessions in date order (each up to what it still owes); what is
-- left over goes on the last one. By the bank (p_code: the month's code) or by hand (staff: method and note).
-- → how much went on the last session beyond what was owed.
create function private.pay_series_month(p_series bigint, p_month date, p_amount numeric, p_by_bank boolean,
                                         p_method public.payment_method default 'cash', p_note text default null,
                                         p_code text default null)
returns numeric
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  b public.bookings;
  v_left numeric := round(p_amount);
  v_take numeric;
  v_last bigint;
begin
  for b in select * from private.series_month_bookings(p_series, p_month) loop
    v_last := b.id;
    v_take := least(v_left, greatest(coalesce(b.full_payment, 0) - coalesce(b.bank_transfer, 0) - coalesce(b.cash, 0), 0));
    if v_take > 0 then
      if p_by_bank then
        perform private.bank_pays_booking(b.id, v_take, p_code);
      else
        perform public.booking_record_payment(b.id, v_take, p_method, p_note);
      end if;
      v_left := v_left - v_take;
    end if;
    exit when v_left <= 0;
  end loop;
  if v_left > 0 and v_last is not null then
    if p_by_bank then
      perform private.bank_pays_booking(v_last, v_left, p_code);
    else
      perform public.booking_record_payment(v_last, v_left, p_method, p_note);
    end if;
  end if;
  return greatest(v_left, 0);
end;
$$;

-- -----------------------------------------------------------------------------
-- Planning and booking a series
-- -----------------------------------------------------------------------------
-- Staff: every day of a series to be (p_weekdays, ISO 1 = Monday, from p_from to p_until, today on, not a time
-- already past), with what holds room p_room then and, for a day that clashes, the rooms still free at those
-- times: [{ date, clash: text | null, free_rooms: [{ id, name }] }].
create function public.booking_series_preview(p_room bigint, p_weekdays smallint[], p_start time, p_end time,
                                              p_from date, p_until date)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_today date := public.studio_today();
  v_now time := (now() at time zone 'Asia/Ho_Chi_Minh')::time;
  v jsonb;
begin
  if not public.is_staff() then
    raise exception 'FORBIDDEN: only staff can plan a recurring rental';
  end if;
  if p_room is null or p_weekdays is null or cardinality(p_weekdays) = 0 or p_start is null or p_end is null
     or p_from is null or p_until is null then
    raise exception 'INVALID_INPUT: room, weekdays, times and dates are required';
  end if;
  if p_end <= p_start or p_start < time '08:00' or p_end > time '22:00'
     or extract(minute from p_start) not in (0, 30) or extract(minute from p_end) not in (0, 30) then
    raise exception 'INVALID_INPUT: times are on the half hour, between 08:00 and 22:00, end after start';
  end if;
  if p_until < p_from or p_until > p_from + 366 then
    raise exception 'INVALID_INPUT: a series runs up to a year';
  end if;
  select coalesce(jsonb_agg(jsonb_build_object(
           'date', d.day,
           'clash', private.room_clash_on(p_room, d.day, p_start, p_end, null),
           'free_rooms', case when private.room_clash_on(p_room, d.day, p_start, p_end, null) is null then '[]'::jsonb
                         else (select coalesce(jsonb_agg(jsonb_build_object('id', r.id, 'name', r.name) order by r.id), '[]'::jsonb)
                                 from public.rooms r
                                where r.id <> p_room and private.room_clash_on(r.id, d.day, p_start, p_end, null) is null) end)
         order by d.day), '[]'::jsonb) into v
    from (select g::date as day from generate_series(greatest(p_from, v_today), p_until, interval '1 day') g) d
   where extract(isodow from d.day)::smallint = any (p_weekdays)
     and (d.day > v_today or p_start >= v_now);
  return v;
end;
$$;

-- Staff: books a series. p_days: the days kept, [{ date, room_id?, start?, end? }] — another room or other times for
-- a day that clashed (default: the series' room and times); days left out are skipped. Each day is an ordinary
-- booking (approved, or held with p_status 'pending'; SLOT_TAKEN when its room is taken then), priced as the room
-- says less the discount: p_discount_kind 'percent' (1–99) or 'amount' (VND off each session), with its reason
-- (required). For an account pass p_guest; for a walk-in p_walk_in_name and p_walk_in_phone. Each month gets its
-- payment code. All or nothing. → the series.
create function public.booking_series_create(
  p_guest          uuid,
  p_room           bigint,
  p_weekdays       smallint[],
  p_start          time,
  p_end            time,
  p_from           date,
  p_until          date,
  p_days           jsonb,
  p_status         public.booking_status default 'approved',
  p_discount_kind  text default null,
  p_discount_value numeric default null,
  p_discount_note  text default null,
  p_details        text default null,
  p_walk_in_name   text default null,
  p_walk_in_phone  text default null
)
returns public.booking_series
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  s public.booking_series;
  b public.bookings;
  x record;
  v_name text := nullif(btrim(p_walk_in_name), '');
  v_note text := left(nullif(btrim(p_discount_note), ''), 300);
  v_price numeric;
  v_n integer := 0;
  v_logging text := coalesce(current_setting('oops.activity', true), '');
begin
  if not public.is_staff() then
    raise exception 'FORBIDDEN: only staff can book a recurring rental';
  end if;
  if (p_guest is null) = (v_name is null) then
    raise exception 'INVALID_INPUT: pick an account, or give the walk-in''s name';
  end if;
  if p_guest is null and nullif(btrim(p_walk_in_phone), '') is null then
    raise exception 'INVALID_INPUT: give the walk-in''s phone number';
  end if;
  if p_guest is not null and not exists (select 1 from public.profiles p where p.id = p_guest) then
    raise exception 'NOT_FOUND: user % not found', p_guest;
  end if;
  if p_status not in ('approved', 'pending') then
    raise exception 'INVALID_INPUT: a new booking is approved or pending';
  end if;
  if p_discount_kind is not null then
    if p_discount_kind not in ('percent', 'amount') or p_discount_value is null or p_discount_value <= 0
       or (p_discount_kind = 'percent' and p_discount_value >= 100) then
      raise exception 'INVALID_INPUT: a discount is 1–99 percent, or an amount off each session';
    end if;
    if v_note is null then
      raise exception 'INVALID_INPUT: say why there is a discount';
    end if;
  end if;
  if p_days is null or jsonb_typeof(p_days) <> 'array' or jsonb_array_length(p_days) = 0 then
    raise exception 'INVALID_INPUT: keep at least one day';
  end if;

  insert into public.booking_series (guest_id, walk_in_name, walk_in_phone, room_id, weekdays, start_time, end_time,
                                     starts_on, ends_on, discount_kind, discount_value, discount_note, details)
  values (p_guest, v_name, nullif(btrim(p_walk_in_phone), ''), p_room, p_weekdays, p_start, p_end, p_from, p_until,
          p_discount_kind, case when p_discount_kind is null then null else round(p_discount_value) end,
          case when p_discount_kind is null then null else v_note end, nullif(btrim(p_details), ''))
  returning * into s;

  perform set_config('oops.activity', 'off', true);
  for x in select * from jsonb_to_recordset(p_days) as t(date date, room_id bigint, start time, "end" time) order by 1 loop
    if x.date is null or x.date < p_from or x.date > p_until then
      raise exception 'INVALID_INPUT: % is outside the series', x.date;
    end if;
    b := private.insert_booking(coalesce(x.room_id, p_room), x.date, coalesce(x.start, p_start), coalesce(x."end", p_end),
                                p_details, p_guest, 'approved', v_name, p_walk_in_phone);
    v_price := case p_discount_kind
                 when 'percent' then round(b.list_price * (100 - p_discount_value) / 100 / 1000) * 1000
                 when 'amount' then greatest(b.list_price - round(p_discount_value), 0)
                 else b.full_payment end;
    update public.bookings
       set series_id = s.id,
           status = p_status,
           full_payment = v_price,
           deposit = round(v_price * 0.5),
           price_note = case when v_price is distinct from b.list_price then v_note else price_note end
     where id = b.id;
    v_n := v_n + 1;
  end loop;
  insert into public.booking_series_bills (series_id, month, payment_code)
  select s.id, m.month, private.new_payment_code()
    from (select distinct date_trunc('month', b2.date)::date as month from public.bookings b2 where b2.series_id = s.id) m;
  perform set_config('oops.activity', v_logging, true);

  insert into public.activity_log (actor_id, actor_name, actor_role, area, action, entity, entity_id, subject_id, label, meta)
  select auth.uid(), private.person_name(auth.uid()), (select p.role from public.profiles p where p.id = auth.uid()),
         'bookings', 'series_created', 'booking_series', s.id::text, s.guest_id, private.series_who(s),
         jsonb_strip_nulls(jsonb_build_object(
           'room', (select r.name from public.rooms r where r.id = s.room_id), 'weekdays', to_jsonb(s.weekdays),
           'start', s.start_time, 'end', s.end_time, 'from', s.starts_on, 'until', s.ends_on, 'sessions', v_n,
           'discount_kind', s.discount_kind, 'discount_value', s.discount_value, 'reason', s.discount_note));
  return s;
end;
$$;

-- -----------------------------------------------------------------------------
-- Paying by month
-- -----------------------------------------------------------------------------
-- A series for staff, or for its own guest; NOT_FOUND otherwise (existence isn't revealed).
create function private.series_for_caller(p_series bigint)
returns public.booking_series
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  s public.booking_series;
begin
  select * into s from public.booking_series where id = p_series;
  -- A walk-in's series has no guest: only staff see it (a null guest never matches the caller).
  if not found or not (public.is_staff() or private.is_service_context() or (s.guest_id is not null and s.guest_id = auth.uid())) then
    raise exception 'NOT_FOUND: no such recurring rental';
  end if;
  return s;
end;
$$;

-- The series and its months: { series: { …, who, room }, months: [{ month, code, sessions, total, paid, balance }],
-- sessions, ahead } (sessions that still count; those still ahead). Staff or its guest.
create function public.booking_series_summary(p_series bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  s public.booking_series;
begin
  s := private.series_for_caller(p_series);
  return jsonb_build_object(
    'series', to_jsonb(s) || jsonb_build_object('who', private.series_who(s),
                                                'room', (select r.name from public.rooms r where r.id = s.room_id)),
    'months', (select coalesce(jsonb_agg(jsonb_build_object(
                 'month', x.month, 'code', x.payment_code,
                 'sessions', (select count(*) from private.series_month_bookings(s.id, x.month)),
                 'total', (select coalesce(sum(b.full_payment), 0) from private.series_month_bookings(s.id, x.month) b),
                 'paid', (select coalesce(sum(coalesce(b.bank_transfer, 0) + coalesce(b.cash, 0)), 0)
                            from private.series_month_bookings(s.id, x.month) b),
                 'balance', private.series_month_balance(s.id, x.month)) order by x.month), '[]'::jsonb)
                 from public.booking_series_bills x where x.series_id = s.id),
    'sessions', (select count(*) from public.bookings b where b.series_id = s.id and b.status in ('pending', 'approved', 'completed')),
    'ahead', (select count(*) from public.bookings b where b.series_id = s.id and b.status in ('pending', 'approved', 'completed')
                and b.date >= public.studio_today()));
end;
$$;

-- Staff: money taken for a month by hand (cash, or a transfer seen by hand), up to what it still owes; spread over its
-- sessions in date order, each with its payment line. → the month's balance after.
create function public.booking_series_record_payment(p_series bigint, p_month date, p_amount numeric,
                                                     p_method public.payment_method default 'cash', p_note text default null)
returns numeric
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  s public.booking_series;
  v_month date := date_trunc('month', p_month)::date;
begin
  if not public.is_staff() then
    raise exception 'FORBIDDEN: only staff can record payments';
  end if;
  s := private.series_for_caller(p_series);
  if p_amount is null or round(p_amount) <= 0 then
    raise exception 'INVALID_INPUT: the amount must be more than zero';
  end if;
  if round(p_amount) > private.series_month_balance(s.id, v_month) then
    raise exception 'INVALID_INPUT: more than the month still owes (%)', private.series_month_balance(s.id, v_month);
  end if;
  perform private.pay_series_month(s.id, v_month, p_amount, false, coalesce(p_method, 'cash'), p_note);
  return private.series_month_balance(s.id, v_month);
end;
$$;

-- Sandbox: a pretend transfer of what a month still owes, with its code (staff or the series' guest).
create function public.booking_series_simulate_transfer(p_series bigint, p_month date)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  s public.booking_series;
  x public.booking_series_bills;
  v_due numeric;
  v_id bigint;
begin
  if not public.tuition_sandbox() then
    raise exception 'FORBIDDEN: simulated transfers only work in the demo';
  end if;
  s := private.series_for_caller(p_series);
  select * into x from public.booking_series_bills where series_id = s.id and month = date_trunc('month', p_month)::date for update;
  if not found then
    raise exception 'NOT_FOUND: no such month in this rental';
  end if;
  v_due := private.series_month_balance(s.id, x.month);
  if v_due <= 0 then
    raise exception 'INVALID_STATE: nothing is left to pay for that month';
  end if;
  insert into public.bank_transfers (provider, provider_ref, amount, content)
  values ('demo', gen_random_uuid()::text, v_due, x.payment_code || ' thue phong thang ' || to_char(x.month, 'MM/YYYY'))
  returning id into v_id;
  perform private.match_transfer(v_id);
  return (select jsonb_build_object('transfer_id', t.id, 'status', t.status, 'series_id', t.series_id, 'note', t.note)
            from public.bank_transfers t where t.id = v_id);
end;
$$;

-- Matches a stored transfer by the OOPS code in its content: a tuition invoice, a booking, or a month of a recurring
-- rental (its sessions in date order).
create or replace function private.match_transfer(p_transfer bigint)
returns void
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  t public.bank_transfers;
  v public.tuition_invoices;
  b public.bookings;
  x public.booking_series_bills;
  v_code text;
  v_due numeric;
  v_over numeric;
begin
  select * into t from public.bank_transfers where id = p_transfer for update;
  v_code := substring(upper(regexp_replace(t.content, '[^A-Za-z0-9]', '', 'g')) from 'OOPS[2-9A-HJ-NP-Z]{6}');
  if v_code is null then
    update public.bank_transfers set status = 'unmatched', note = 'No invoice code in the transfer content.' where id = t.id;
    return;
  end if;

  select * into v from public.tuition_invoices where payment_code = v_code for update;
  if not found then
    select * into b from public.bookings where payment_code = v_code for update;
    if not found then
      select * into x from public.booking_series_bills where payment_code = v_code for update;
      if not found then
        update public.bank_transfers set status = 'unmatched', note = format('Unknown invoice code %s.', v_code) where id = t.id;
        return;
      end if;
      if not exists (select 1 from private.series_month_bookings(x.series_id, x.month)) then
        update public.bank_transfers
           set status = 'unmatched', note = format('No session of rental #%s is left in %s.', x.series_id, to_char(x.month, 'MM/YYYY'))
         where id = t.id;
        return;
      end if;
      v_due := private.series_month_balance(x.series_id, x.month);
      v_over := private.pay_series_month(x.series_id, x.month, t.amount, true, 'transfer', null, v_code);
      update public.bank_transfers
         set status = 'matched', series_id = x.series_id, series_month = x.month,
             note = case when t.amount < v_due then format('Partial payment: %s still due.', v_due - t.amount)
                         when v_over > 0 then format('Paid %s more than was due.', v_over) end
       where id = t.id;
      return;
    end if;
    if b.status in ('rejected', 'cancelled') then
      update public.bank_transfers
         set status = 'unmatched', note = format('Booking #%s is %s.', b.id, b.status)
       where id = t.id;
      return;
    end if;
    v_due := greatest(coalesce(b.full_payment, 0) - coalesce(b.bank_transfer, 0) - coalesce(b.cash, 0), 0);
    perform private.bank_pays_booking(b.id, t.amount, v_code);
    update public.bank_transfers
       set status = 'matched', booking_id = b.id,
           note = case when t.amount > v_due then format('Paid %s more than was due.', t.amount - v_due) end
     where id = t.id;
    return;
  end if;

  if v.status = 'void' then
    perform private.reinstate(v.id);
    select * into v from public.tuition_invoices where id = v.id;
  end if;
  if v.status <> 'unpaid' then
    update public.bank_transfers
       set status = 'unmatched', note = format('Invoice %s is already %s.', v_code, v.status)
     where id = t.id;
    return;
  end if;

  v_due := v.amount - v.paid_amount;
  perform private.apply_payment(v.id, t.amount, 'transfer', t.received_at);
  update public.bank_transfers
     set status = 'matched', invoice_id = v.id,
         note = case when t.amount < v_due then format('Partial payment: %s still due.', v_due - t.amount)
                     when t.amount > v_due then format('Paid %s more than was due.', t.amount - v_due) end
   where id = t.id;
end;
$$;

-- -----------------------------------------------------------------------------
-- Ending a series early
-- -----------------------------------------------------------------------------
-- Staff: cancels the series' sessions still ahead (not started), each as cancel_booking does — p_by_studio for the
-- studio's side (everything paid goes back), else the renter's (the cancellation policy). → how many.
create function public.booking_series_cancel_rest(p_series bigint, p_by_studio boolean default false, p_note text default null)
returns integer
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  s public.booking_series;
  b public.bookings;
  v_n integer := 0;
begin
  if not public.is_staff() then
    raise exception 'FORBIDDEN: only staff can end a recurring rental';
  end if;
  s := private.series_for_caller(p_series);
  for b in select * from public.bookings x
            where x.series_id = s.id and x.status in ('pending', 'approved', 'completed')
              and private.booking_starts_at(x) > now()
            order by x.date, x.start_time loop
    perform public.cancel_booking(b.id, coalesce(p_by_studio, false), null, p_note);
    v_n := v_n + 1;
  end loop;
  return v_n;
end;
$$;

