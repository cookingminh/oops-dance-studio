create function private.tuition_month(p_day date)
returns date
language sql
immutable
set search_path = ''
as $$ select date_trunc('month', p_day)::date; $$;

-- Pay by the settings' due day; an invoice created late still gets a week.
create function private.tuition_due_date(p_month date, p_today date)
returns date
language sql
stable
set search_path = ''
as $$
  select greatest(p_month + (s.due_day - 1), p_today + 7)
    from public.tuition_settings s where s.id = 1;
$$;

create function private.person_name(p_id uuid)
returns text
language sql
stable
set search_path = ''
as $$
  select coalesce(nullif(btrim(p.full_name), ''), p.username, p.email, '')
    from public.profiles p where p.id = p_id;
$$;

-- Bills one enrolment for a month (no-op when the invoice exists). Returns the invoice id or null.
create function private.bill_enrolment(p_student uuid, p_class bigint, p_month date, p_renewal public.tuition_renewal, p_today date)
returns bigint
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_id bigint;
begin
  insert into public.tuition_invoices (student_id, class_id, student_name, class_name, month, amount, renewal, due_date)
  select p_student, c.id, coalesce(private.person_name(p_student), ''), c.name, p_month, c.price, p_renewal,
         private.tuition_due_date(p_month, p_today)
    from public.classes c
   where c.id = p_class
  on conflict on constraint tuition_invoices_one_per_month do nothing
  returning id into v_id;
  return v_id;
end;
$$;

-- Every current enrolment gets an invoice for p_month. Returns how many were created.
create function private.open_month(p_month date, p_today date)
returns integer
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_count integer;
begin
  insert into public.tuition_invoices (student_id, class_id, student_name, class_name, month, amount, renewal, due_date)
  select cs.student_id, c.id, coalesce(private.person_name(cs.student_id), ''), c.name, p_month, c.price,
         -- someone who joins during p_month (or later) has already said yes
         case when cs.joined_at >= p_month then 'continue'::public.tuition_renewal end,
         private.tuition_due_date(p_month, p_today)
    from public.class_students cs
    join public.classes c on c.id = cs.class_id
  on conflict on constraint tuition_invoices_one_per_month do nothing;
  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

-- Adds a payment. Paying means continuing, so an unanswered renewal becomes 'continue'.
create function private.apply_payment(p_invoice bigint, p_amount numeric, p_method public.payment_method, p_at timestamptz)
returns void
language sql
volatile
security definer
set search_path = ''
as $$
  update public.tuition_invoices i
     set paid_amount = i.paid_amount + p_amount,
         method      = p_method,
         status      = case when i.paid_amount + p_amount >= i.amount then 'paid'::public.tuition_status else i.status end,
         paid_at     = case when i.paid_amount + p_amount >= i.amount then p_at else i.paid_at end,
         renewal     = coalesce(i.renewal, 'continue'),
         updated_by  = auth.uid()
   where i.id = p_invoice;
$$;

-- An invoice that was cancelled because the student stopped or didn't renew comes back
-- (the student is back in the class) when they pay late or change their mind.
create function private.reinstate(p_invoice bigint)
returns boolean
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v public.tuition_invoices;
  v_month date := private.tuition_month(public.studio_today());
begin
  select * into v from public.tuition_invoices where id = p_invoice for update;
  if v.status <> 'void' or v.void_reason not in ('stopped', 'not_renewed')
     or v.month < v_month or v.student_id is null or v.class_id is null then
    return false;
  end if;
  update public.tuition_invoices
     set status = 'unpaid', void_reason = null, renewal = 'continue', updated_by = auth.uid()
   where id = p_invoice;
  -- Back in the class for the current month (the enrolment trigger leaves this invoice alone:
  -- it is unpaid again).
  if v.month = v_month then
    insert into public.class_students (class_id, student_id)
    values (v.class_id, v.student_id)
    on conflict do nothing;
  end if;
  return true;
end;
$$;

-- Matches a stored transfer to an invoice by the OOPS code in its content.
create function private.match_transfer(p_transfer bigint)
returns void
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  t public.bank_transfers;
  v public.tuition_invoices;
  v_code text;
  v_due numeric;
begin
  select * into t from public.bank_transfers where id = p_transfer for update;
  v_code := substring(upper(regexp_replace(t.content, '[^A-Za-z0-9]', '', 'g')) from 'OOPS[2-9A-HJ-NP-Z]{6}');
  if v_code is null then
    update public.bank_transfers set status = 'unmatched', note = 'No invoice code in the transfer content.' where id = t.id;
    return;
  end if;

  select * into v from public.tuition_invoices where payment_code = v_code for update;
  if not found then
    update public.bank_transfers set status = 'unmatched', note = format('Unknown invoice code %s.', v_code) where id = t.id;
    return;
  end if;
  if v.status = 'void' then
    perform private.reinstate(v.id);
    select * into v from public.tuition_invoices where id = v.id;
  end if;
  if v.status <> 'unpaid' then
    update public.bank_transfers
       set status = 'unmatched', note = format('Invoice %s is already %s.', v_code, v.status)
     where id = t.id;
    return;
  end if;

  v_due := v.amount - v.paid_amount;
  perform private.apply_payment(v.id, t.amount, 'transfer', t.received_at);
  update public.bank_transfers
     set status = 'matched', invoice_id = v.id,
         note = case when t.amount < v_due then format('Partial payment: %s still due.', v_due - t.amount)
                     when t.amount > v_due then format('Paid %s more than was due.', t.amount - v_due) end
   where id = t.id;
end;
$$;

-- -----------------------------------------------------------------------------
-- Enrolment triggers
-- -----------------------------------------------------------------------------
create function private.on_enrolment_added()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_today date := public.studio_today();
  v_month date := private.tuition_month(v_today);
begin
  -- Re-added this month after being removed (or after stopping): the cancelled invoices come back.
  update public.tuition_invoices
     set status = 'unpaid', void_reason = null,
         renewal = case when month = v_month then 'continue'::public.tuition_renewal end
   where student_id = new.student_id and class_id = new.class_id
     and month >= v_month and status = 'void';
  perform private.bill_enrolment(new.student_id, new.class_id, v_month, 'continue', v_today);
  if extract(day from v_today) >= (select s.invoice_day from public.tuition_settings s where s.id = 1) then
    perform private.bill_enrolment(new.student_id, new.class_id, (v_month + interval '1 month')::date, null, v_today);
  end if;
  return null;
end;
$$;

create function private.on_enrolment_removed()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.tuition_invoices
     set status = 'void', void_reason = 'removed'
   where student_id = old.student_id and class_id = old.class_id
     and month >= private.tuition_month(public.studio_today())
     and status = 'unpaid' and paid_amount = 0;
  return null;
end;
$$;

create trigger bill_new_enrolment after insert on public.class_students
  for each row execute function private.on_enrolment_added();
create trigger void_removed_enrolment after delete on public.class_students
  for each row execute function private.on_enrolment_removed();

-- Deleting a class or a person keeps paid history (names are on the invoice) and drops
-- invoices that never had money on them.
create function private.drop_unpaid_invoices()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_table_name = 'classes' then
    delete from public.tuition_invoices where class_id = old.id and status in ('unpaid', 'void') and paid_amount = 0;
  else
    delete from public.tuition_invoices where student_id = old.id and status in ('unpaid', 'void') and paid_amount = 0;
  end if;
  return old;
end;
$$;

create trigger drop_unpaid_invoices before delete on public.classes
  for each row execute function private.drop_unpaid_invoices();
create trigger drop_unpaid_invoices before delete on public.profiles
  for each row execute function private.drop_unpaid_invoices();

