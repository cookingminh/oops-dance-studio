-- Locked row for the caller: their own invoice (p_own) or any invoice for staff.
create function private.invoice_for_caller(p_invoice bigint, p_own boolean)
returns public.tuition_invoices
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v public.tuition_invoices;
begin
  select * into v from public.tuition_invoices where id = p_invoice for update;
  if not found
     or not (public.is_staff() or private.is_service_context()
             or (p_own and v.student_id = auth.uid())) then
    raise exception 'NOT_FOUND: no such invoice';
  end if;
  return v;
end;
$$;

-- "Continue" or "stop" for an invoice's month (the student for themself, or staff).
create function public.tuition_set_renewal(p_invoice bigint, p_decision public.tuition_renewal)
returns public.tuition_invoices
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v public.tuition_invoices := private.invoice_for_caller(p_invoice, true);
  v_month date := private.tuition_month(public.studio_today());
begin
  if v.month < v_month then
    raise exception 'INVALID_STATE: that month is over';
  end if;

  if p_decision = 'stop' then
    if v.status not in ('unpaid', 'void') or v.paid_amount > 0 then
      raise exception 'INVALID_STATE: this month is already paid; ask the studio to stop it';
    end if;
    update public.tuition_invoices
       set status = 'void', void_reason = 'stopped', renewal = 'stop', updated_by = auth.uid()
     where id = v.id;
    -- Stopping the running month ends the enrolment now; next month's ends when it starts.
    if v.month = v_month then
      delete from public.class_students where class_id = v.class_id and student_id = v.student_id;
    end if;
  else
    if v.status = 'void' then
      if not private.reinstate(v.id) then
        raise exception 'INVALID_STATE: this invoice can''t be reopened; ask the studio';
      end if;
    else
      update public.tuition_invoices set renewal = 'continue', updated_by = auth.uid() where id = v.id;
    end if;
  end if;

  select * into v from public.tuition_invoices where id = p_invoice;
  return v;
end;
$$;

-- Staff record a payment: cash at the desk, or a transfer they saw in the bank app.
-- p_amount defaults to what is still due.
create function public.tuition_mark_paid(
  p_invoice bigint,
  p_method  public.payment_method default 'cash',
  p_amount  numeric default null,
  p_note    text default null
)
returns public.tuition_invoices
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v public.tuition_invoices;
  v_amount numeric;
begin
  if not (public.is_staff() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only staff can record payments';
  end if;
  v := private.invoice_for_caller(p_invoice, false);
  if v.status = 'void' then
    perform private.reinstate(v.id);
    select * into v from public.tuition_invoices where id = p_invoice;
  end if;
  if v.status <> 'unpaid' then
    raise exception 'INVALID_STATE: this invoice is %', v.status;
  end if;
  v_amount := coalesce(p_amount, v.amount - v.paid_amount);
  if v_amount <= 0 then
    raise exception 'INVALID_INPUT: the amount must be more than 0';
  end if;
  perform private.apply_payment(v.id, v_amount, p_method, now());
  if nullif(btrim(p_note), '') is not null then
    update public.tuition_invoices set note = left(btrim(p_note), 300) where id = v.id;
  end if;
  select * into v from public.tuition_invoices where id = p_invoice;
  return v;
end;
$$;

-- Staff undo a payment recorded by mistake. Transfers that paid it go back to the inbox.
create function public.tuition_undo_payment(p_invoice bigint)
returns public.tuition_invoices
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v public.tuition_invoices;
begin
  if not (public.is_staff() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only staff can undo payments';
  end if;
  v := private.invoice_for_caller(p_invoice, false);
  if v.paid_amount = 0 or v.status not in ('paid', 'unpaid') then
    raise exception 'INVALID_STATE: nothing has been paid on this invoice';
  end if;
  update public.tuition_invoices
     set status = 'unpaid', paid_amount = 0, method = null, paid_at = null, updated_by = auth.uid()
   where id = v.id;
  update public.bank_transfers
     set status = 'unmatched', invoice_id = null, note = 'Payment undone by staff.'
   where invoice_id = v.id;
  select * into v from public.tuition_invoices where id = p_invoice;
  return v;
end;
$$;

-- Staff waive a month (scholarship, injury, staff family, …) or bring a waived/cancelled one back.
