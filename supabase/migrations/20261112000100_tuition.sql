-- =============================================================================
-- Tuition (học phí) and the finance report — api-contract §3 "Tuition", §5 tuition_* / finance_*
--
--   One invoice per student, class and month (tuition_invoices), at the class's monthly price.
--   * Enrolling a student (class_students insert) bills the current month straight away.
--   * From `invoice_day` (default the 25th) next month's invoices open: that is the renewal.
--     The student pays (bank transfer with the invoice's code, or cash at the desk) or answers
--     "continue" / "stop". Staff can answer for them, and can open the renewal earlier.
--   * Bank transfers: the bank webhook (Edge Function `bank-webhook`, SePay format) calls
--     tuition_record_transfer(); a transfer whose content holds an invoice code pays that
--     invoice. Anything else waits in bank_transfers as 'unmatched' for staff to assign or ignore.
--   * Daily job tuition_run_cycle(): bills enrolments that have no invoice for the month yet,
--     opens next month's invoices from invoice_day, cancels ('void', not_renewed) invoices that
--     are still unpaid and unanswered after their due date, and ends the enrolment of everyone
--     whose invoice for the current month is void (they stopped or didn't renew).
--   * Removing a student from a class voids their unpaid invoices from this month on.
--   Invoices keep the student's and the class's name, so deleting either keeps paid history.
--
--   Writes go through the tuition_* functions only (RLS: students read their own invoices,
--   staff read everything). The finance_* report functions are admin only.
-- =============================================================================

create type public.tuition_status as enum ('unpaid', 'paid', 'waived', 'void');
create type public.tuition_renewal as enum ('continue', 'stop');
create type public.payment_method as enum ('transfer', 'cash');

-- -----------------------------------------------------------------------------
-- Settings: the bank account shown on the VietQR code, and the monthly calendar.
-- -----------------------------------------------------------------------------
create table public.tuition_settings (
  id           smallint primary key default 1 check (id = 1),
  bank_code    text check (bank_code ~ '^[A-Za-z0-9]{2,20}$'),            -- VietQR bank id: BIN (970436) or short name (VCB)
  bank_name    text check (char_length(btrim(bank_name)) between 1 and 80),
  account_no   text check (account_no ~ '^[0-9A-Za-z]{4,30}$'),
  account_name text check (char_length(btrim(account_name)) between 1 and 80),
  invoice_day  smallint not null default 25 check (invoice_day between 15 and 28), -- next month's invoices open
  due_day      smallint not null default 10 check (due_day between 1 and 28),      -- pay or answer by this day
  updated_at   timestamptz not null default now()
);
insert into public.tuition_settings (id) values (1);

create trigger set_updated_at before update on public.tuition_settings
  for each row execute function private.set_updated_at();

-- -----------------------------------------------------------------------------
-- Invoices
-- -----------------------------------------------------------------------------
-- 'OOPS' + 6 characters without 0/O/1/I, e.g. OOPS7K3M9Q: short enough to type into a bank app.
create function private.new_payment_code()
returns text
language plpgsql
volatile
set search_path = ''
as $$
declare
  v_chars constant text := '23456789ABCDEFGHJKLMNPQRSTUVWXYZ';
  v_code text;
begin
  loop
    v_code := 'OOPS' || (select string_agg(substr(v_chars, 1 + floor(random() * 32)::int, 1), '')
                           from generate_series(1, 6));
    exit when not exists (select 1 from public.tuition_invoices i where i.payment_code = v_code);
  end loop;
  return v_code;
end;
$$;

create table public.tuition_invoices (
  id           bigint generated by default as identity primary key,
  student_id   uuid references public.profiles (id) on delete set null,
  class_id     bigint references public.classes (id) on delete set null,
  student_name text not null default '',
  class_name   text not null default '',
  month        date not null check (month = date_trunc('month', month)::date),
  amount       numeric(12, 0) not null check (amount >= 0),
  paid_amount  numeric(12, 0) not null default 0 check (paid_amount >= 0),
  status       public.tuition_status not null default 'unpaid',
  renewal      public.tuition_renewal,          -- "continue this month?"; null = no answer yet
  method       public.payment_method,           -- how it was (last) paid
  payment_code text not null unique default private.new_payment_code()
               check (payment_code ~ '^OOPS[2-9A-HJ-NP-Z]{6}$'),
  due_date     date not null,
  paid_at      timestamptz,
  void_reason  text check (void_reason in ('stopped', 'not_renewed', 'removed')),
  note         text check (char_length(note) <= 300),
  updated_by   uuid references public.profiles (id) on delete set null,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  constraint tuition_invoices_one_per_month unique (student_id, class_id, month),
  constraint tuition_invoices_void_reason check ((status = 'void') = (void_reason is not null)),
  constraint tuition_invoices_paid_at check (status <> 'paid' or paid_at is not null)
);
create index tuition_invoices_month_idx on public.tuition_invoices (month);
create index tuition_invoices_class_month_idx on public.tuition_invoices (class_id, month);
create index tuition_invoices_student_idx on public.tuition_invoices (student_id);

create trigger set_updated_at before update on public.tuition_invoices
  for each row execute function private.set_updated_at();

