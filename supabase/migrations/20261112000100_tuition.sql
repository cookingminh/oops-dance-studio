create function public.tuition_reopen(p_invoice bigint)
returns public.tuition_invoices
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v public.tuition_invoices;
begin
  if not (public.is_staff() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only staff can reopen invoices';
  end if;
  v := private.invoice_for_caller(p_invoice, false);
  if v.status = 'waived' then
    update public.tuition_invoices set status = 'unpaid', updated_by = auth.uid() where id = v.id;
  elsif v.status <> 'void' or not private.reinstate(v.id) then
    raise exception 'INVALID_STATE: this invoice can''t be reopened';
  end if;
  select * into v from public.tuition_invoices where id = p_invoice;
  return v;
end;
$$;

-- Staff change what an unpaid invoice asks for (a discount, a pro-rated first month, …).
create function public.tuition_set_amount(p_invoice bigint, p_amount numeric, p_note text default null)
returns public.tuition_invoices
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v public.tuition_invoices;
begin
  if not (public.is_staff() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only staff can change tuition';
  end if;
  v := private.invoice_for_caller(p_invoice, false);
  if v.status <> 'unpaid' then
    raise exception 'INVALID_STATE: only an unpaid invoice can be changed';
  end if;
  if p_amount is null or p_amount <= 0 or p_amount <> round(p_amount) then
    raise exception 'INVALID_INPUT: the amount must be a whole number above 0';
  end if;
  update public.tuition_invoices
     set amount = p_amount,
         status = case when paid_amount >= p_amount then 'paid'::public.tuition_status else status end,
         paid_at = case when paid_amount >= p_amount then now() else paid_at end,
         note = coalesce(left(nullif(btrim(p_note), ''), 300), note),
         updated_by = auth.uid()
   where id = v.id;
  select * into v from public.tuition_invoices where id = p_invoice;
  return v;
end;
$$;

-- Staff open next month's renewal before invoice_day (or bill the current month again after
-- adding enrolments by hand). Only the current or the next month.
create function public.tuition_open_month(p_month date)
returns integer
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_today date := public.studio_today();
  v_month date := private.tuition_month(v_today);
begin
  if not (public.is_staff() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only staff can open a month';
  end if;
  if private.tuition_month(p_month) not in (v_month, (v_month + interval '1 month')::date) then
    raise exception 'INVALID_INPUT: only this month or next month can be opened';
  end if;
  return private.open_month(private.tuition_month(p_month), v_today);
end;
$$;

-- Staff link an unmatched transfer to an invoice (the student wrote no code, or a wrong one).
create function public.tuition_assign_transfer(p_transfer bigint, p_invoice bigint)
returns public.bank_transfers
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  t public.bank_transfers;
  v public.tuition_invoices;
begin
  if not (public.is_staff() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only staff can assign transfers';
  end if;
  select * into t from public.bank_transfers where id = p_transfer for update;
  if not found then
    raise exception 'NOT_FOUND: no such transfer';
  end if;
  if t.status = 'matched' then
    raise exception 'INVALID_STATE: this transfer already paid an invoice';
  end if;
  v := private.invoice_for_caller(p_invoice, false);
  if v.status = 'void' then
    perform private.reinstate(v.id);
    select * into v from public.tuition_invoices where id = p_invoice;
  end if;
  if v.status <> 'unpaid' then
    raise exception 'INVALID_STATE: this invoice is %', v.status;
  end if;
  perform private.apply_payment(v.id, t.amount, 'transfer', t.received_at);
  update public.bank_transfers
     set status = 'matched', invoice_id = v.id, note = 'Assigned by staff.'
   where id = t.id
  returning * into t;
  return t;
end;
$$;

