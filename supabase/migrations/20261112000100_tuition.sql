-- -----------------------------------------------------------------------------
-- The monthly cycle (pg_cron daily; staff may run it too). p_today is for tests and only
-- honoured in a service context.
-- -----------------------------------------------------------------------------
create function public.tuition_run_cycle(p_today date default null)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_today  date;
  v_month  date;
  v_next   date;
  v_billed integer;
  v_opened integer := 0;
  v_voided integer;
  v_ended  integer;
begin
  if not (private.is_service_context() or public.is_staff()) then
    raise exception 'FORBIDDEN: only staff can run the tuition cycle';
  end if;
  v_today := case when private.is_service_context() then coalesce(p_today, public.studio_today()) else public.studio_today() end;
  v_month := private.tuition_month(v_today);
  v_next  := (v_month + interval '1 month')::date;

  -- 1. Every enrolment has an invoice for this month.
  v_billed := private.open_month(v_month, v_today);

  -- 2. Next month's renewal opens on invoice_day.
  if extract(day from v_today) >= (select s.invoice_day from public.tuition_settings s where s.id = 1) then
    v_opened := private.open_month(v_next, v_today);
  end if;

  -- 3. Unpaid, unanswered and past due: not renewed.
  update public.tuition_invoices
     set status = 'void', void_reason = 'not_renewed'
   where status = 'unpaid' and renewal is null and paid_amount = 0
     and due_date < v_today and month <= v_month;
  get diagnostics v_voided = row_count;

  -- 4. Whoever has a cancelled invoice for the running month leaves the class.
  delete from public.class_students cs
   using public.tuition_invoices i
   where i.student_id = cs.student_id and i.class_id = cs.class_id
     and i.month = v_month and i.status = 'void';
  get diagnostics v_ended = row_count;

  return jsonb_build_object('today', v_today, 'billed', v_billed, 'opened', v_opened,
                            'not_renewed', v_voided, 'enrolments_ended', v_ended);
end;
$$;

-- -----------------------------------------------------------------------------
-- Finance report (admin only)
-- -----------------------------------------------------------------------------
-- One row per month from p_from to p_to (at most 36 months).
--   tuition_*: by the month the invoice is for. collected = money received on it.
--   bookings_revenue: real income of approved/completed room bookings in the month.
--   payroll_cost: the month's payroll total (payslip snapshot when finalized).
--   enrolments_new / renewed / ended: class memberships that started, carried on from the
--   previous month, or stopped (stopped, not renewed, removed) in the month.
create function public.finance_monthly(p_from date, p_to date)
returns table (
  month               date,
  tuition_billed      numeric,
  tuition_collected   numeric,
  tuition_outstanding numeric,
  tuition_waived      numeric,
  transfer_amount     numeric,
  cash_amount         numeric,
  bookings_revenue    numeric,
  payroll_cost        numeric,
  revenue             numeric,
  profit              numeric,
  students_active     integer,
  enrolments_active   integer,
  enrolments_new      integer,
  enrolments_renewed  integer,
  enrolments_ended    integer,
  invoices_overdue    integer
)
language plpgsql
stable
security definer
set search_path = ''
as $$
#variable_conflict use_column
declare
  v_from date := private.tuition_month(p_from);
  v_to   date := private.tuition_month(p_to);
  v_today date := public.studio_today();
begin
  if not (public.is_admin() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only an admin can see the finance report';
  end if;
  if v_from is null or v_to is null or v_from > v_to or v_to > v_from + interval '35 months' then
    raise exception 'INVALID_INPUT: pick up to 36 months, oldest first';
  end if;

  return query
  with months as (
    select g::date as m from generate_series(v_from, v_to, interval '1 month') g
  ), inv as (
    select i.*, (i.status <> 'void') as live,
           exists (select 1 from public.tuition_invoices p
                    where p.status <> 'void' and p.student_id = i.student_id and p.class_id = i.class_id
                      and p.month = (i.month - interval '1 month')::date) as had_prev
      from public.tuition_invoices i
     where i.month between v_from and v_to
  ), t as (
    select m.m,
           coalesce(sum(i.amount) filter (where i.status in ('unpaid', 'paid')), 0) as billed,
           coalesce(sum(i.paid_amount), 0) as collected,
           coalesce(sum(i.amount - i.paid_amount) filter (where i.status = 'unpaid'), 0) as outstanding,
           coalesce(sum(i.amount) filter (where i.status = 'waived'), 0) as waived,
           coalesce(sum(i.paid_amount) filter (where i.method = 'transfer'), 0) as by_transfer,
           coalesce(sum(i.paid_amount) filter (where i.method = 'cash'), 0) as by_cash,
           count(distinct i.student_id) filter (where i.live)::integer as students,
           count(*) filter (where i.live)::integer as active,
           count(*) filter (where i.live and not i.had_prev)::integer as fresh,
           count(*) filter (where i.live and i.had_prev)::integer as renewed,
           count(*) filter (where not i.live)::integer as ended,
           count(*) filter (where i.status = 'unpaid' and i.due_date < v_today)::integer as overdue
      from months m
      left join inv i on i.month = m.m
     group by m.m
  ), b as (
    select m.m, coalesce(sum(bk.real_income), 0) as income
      from months m
      left join public.bookings bk
        on bk.date >= m.m and bk.date < (m.m + interval '1 month')::date
       and bk.status in ('approved', 'completed')
     group by m.m
  )
  select t.m, t.billed, t.collected, t.outstanding, t.waived, t.by_transfer, t.by_cash,
         b.income, pc.cost,
         t.collected + b.income,
         t.collected + b.income - pc.cost,
         t.students, t.active, t.fresh, t.renewed, t.ended, t.overdue
    from t
    join b on b.m = t.m
    cross join lateral (select coalesce(sum(p.total), 0) as cost from public.payroll_month(t.m) p) pc
   order by t.m;
end;
$$;

-- Per class for one month: who's in it, what it brought in, what its sessions cost.
create function public.finance_by_class(p_month date)
returns table (
  class_id        bigint,
  class_name      text,
  instructor_name text,
  students        integer,
  billed          numeric,
  collected       numeric,
  outstanding     numeric,
  sessions        integer,
  instructor_pay  numeric,
  margin          numeric
)
language plpgsql
stable
security definer
set search_path = ''
as $$
#variable_conflict use_column
declare
  v_month date := private.tuition_month(p_month);
  v_next  date := (private.tuition_month(p_month) + interval '1 month')::date;
  v_rate  numeric := (select s.default_session_rate from public.payroll_settings s where s.id = 1);
begin
  if not (public.is_admin() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only an admin can see the finance report';
  end if;

  return query
  with inv as (
    select i.class_id as cid, max(i.class_name) as cname,
           count(*) filter (where i.status <> 'void')::integer as n,
           coalesce(sum(i.amount) filter (where i.status in ('unpaid', 'paid')), 0) as billed,
           coalesce(sum(i.paid_amount), 0) as collected,
           coalesce(sum(i.amount - i.paid_amount) filter (where i.status = 'unpaid'), 0) as outstanding
      from public.tuition_invoices i
     where i.month = v_month
     group by i.class_id
  ), sess as (
    select a.class_id as cid, count(*)::integer as n, sum(coalesce(r.session_rate, v_rate)) as pay
      from public.instructor_attendance a
      left join public.class_pay_rates r on r.class_id = a.class_id
     where a.status = 'completed' and a.date >= v_month and a.date < v_next
     group by a.class_id
  ), ids as (
    select cid from inv union select cid from sess
  )
  select ids.cid,
         coalesce(c.name, inv.cname, ''),
         coalesce(nullif(btrim(p.full_name), ''), p.username, ''),
         coalesce(inv.n, 0),
         coalesce(inv.billed, 0),
         coalesce(inv.collected, 0),
         coalesce(inv.outstanding, 0),
         coalesce(sess.n, 0),
         coalesce(sess.pay, 0),
         coalesce(inv.collected, 0) - coalesce(sess.pay, 0)
    from ids
    left join inv on inv.cid is not distinct from ids.cid
    left join sess on sess.cid = ids.cid
    left join public.classes c on c.id = ids.cid
    left join public.profiles p on p.id = c.instructor_id
   order by coalesce(inv.collected, 0) desc, 2;
end;
$$;

-- -----------------------------------------------------------------------------
-- Demo data (seed.sql and scripts/seed-demo.mjs; service role on a sandbox only).
-- Every current enrolment is billed from the month it joined: past months paid (mostly by
-- transfer, some cash); a few students who left (stopped / not renewed); this month part paid,
-- some overdue who promised to pay, the rest still open; next month's renewal already open with
-- a few answers; a small inbox of bank transfers. The demo guest (guest@demo.oopsdance.test)
-- has one class paid and one open, so the QR flow can be tried.
-- -----------------------------------------------------------------------------
create function public.seed_demo_tuition()
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_today date := public.studio_today();
  v_month date := private.tuition_month(v_today);
  v_next  date := (private.tuition_month(v_today) + interval '1 month')::date;
  v_guest uuid := (select id from public.profiles where email = 'guest@demo.oopsdance.test');
  r record;
  m date;
  h integer;
  k integer;
  v_paid_at timestamptz;
begin
  if not (private.is_service_context() and public.tuition_sandbox()) then
    raise exception 'FORBIDDEN: demo tuition is only seeded on a sandbox';
  end if;

  update public.tuition_settings
     set bank_code = coalesce(bank_code, '970436'), bank_name = coalesce(bank_name, 'Vietcombank'),
         account_no = coalesce(account_no, '0000000000'), account_name = coalesce(account_name, 'OOPS DANCE STUDIO DEMO')
   where id = 1;

  -- 1. Past months of every current enrolment, paid.
  for r in
    select cs.student_id, cs.class_id, cs.joined_at, c.price, c.name, private.person_name(cs.student_id) as sname
      from public.class_students cs join public.classes c on c.id = cs.class_id
  loop
    m := private.tuition_month(r.joined_at);
    while m < v_month loop
      h := abs(hashtext(r.student_id::text || r.class_id::text || m::text));
      insert into public.tuition_invoices (student_id, class_id, student_name, class_name, month, amount, paid_amount,
                                           status, renewal, method, due_date, paid_at, created_at)
      values (r.student_id, r.class_id, coalesce(r.sname, ''), r.name, m, r.price, r.price, 'paid', 'continue',
              case when h % 4 = 0 then 'cash' else 'transfer' end::public.payment_method, m + 9,
              ((m + (h % 9)) + time '19:30') at time zone 'Asia/Ho_Chi_Minh',
              ((m - 6) + time '00:10') at time zone 'Asia/Ho_Chi_Minh')
      on conflict on constraint tuition_invoices_one_per_month do nothing;
      m := (m + interval '1 month')::date;
    end loop;
  end loop;

  -- 2. Students who left a class: two paid months, then stopped or didn't renew last month.
  for r in
    select p.id as student_id, c.id as class_id, c.price, c.name, private.person_name(p.id) as sname,
           abs(hashtext(p.email)) as h
      from public.profiles p
      join public.classes c on c.id = (select min(x.id) + abs(hashtext(p.email || 'left')) % greatest(count(*), 1)
                                         from public.classes x)
     where p.role = 'guest' and p.email like '%@demo.oopsdance.test' and p.id is distinct from v_guest
       and abs(hashtext(p.email)) % 3 = 1
       and not exists (select 1 from public.class_students cs where cs.student_id = p.id and cs.class_id = c.id)
  loop
    for k in reverse 3..2 loop
      m := (v_month - make_interval(months => k))::date;
      insert into public.tuition_invoices (student_id, class_id, student_name, class_name, month, amount, paid_amount,
                                           status, renewal, method, due_date, paid_at)
      values (r.student_id, r.class_id, coalesce(r.sname, ''), r.name, m, r.price, r.price, 'paid', 'continue', 'transfer',
              m + 9, ((m + 3 + r.h % 5) + time '20:00') at time zone 'Asia/Ho_Chi_Minh')
      on conflict on constraint tuition_invoices_one_per_month do nothing;
    end loop;
    m := (v_month - interval '1 month')::date;
    insert into public.tuition_invoices (student_id, class_id, student_name, class_name, month, amount, status,
                                         renewal, void_reason, due_date)
    values (r.student_id, r.class_id, coalesce(r.sname, ''), r.name, m, r.price, 'void',
            case when r.h % 2 = 0 then 'stop'::public.tuition_renewal end,
            case when r.h % 2 = 0 then 'stopped' else 'not_renewed' end, m + 9)
    on conflict on constraint tuition_invoices_one_per_month do nothing;
  end loop;

  -- 3. This month: renewals of earlier enrolments are unanswered until paid; then part paid,
  --    a few overdue who promised to pay, the rest open.
  perform private.open_month(v_month, v_today);
  update public.tuition_invoices i
     set renewal = null
    from public.class_students cs
   where i.month = v_month and i.status = 'unpaid' and i.paid_amount = 0
     and cs.student_id = i.student_id and cs.class_id = i.class_id and cs.joined_at < v_month;
  for r in
    select i.* from public.tuition_invoices i
     where i.month = v_month and i.status = 'unpaid' and i.paid_amount = 0
  loop
    h := abs(hashtext(r.payment_code));
    if r.student_id = v_guest then
      -- the demo guest: their first class paid by transfer, the other one open to try the QR flow
      if r.class_id = (select min(cs.class_id) from public.class_students cs where cs.student_id = v_guest) then
        h := 0;
      else
        -- said yes, not paid yet: never dropped by the cycle, at worst overdue
        update public.tuition_invoices set renewal = 'continue' where id = r.id;
        continue;
      end if;
    end if;
    if h % 10 < 6 then
      v_paid_at := least(((v_month + (h % greatest(least(extract(day from v_today)::int, 9), 1))) + time '20:15')
                         at time zone 'Asia/Ho_Chi_Minh', now() - interval '1 hour');
      update public.tuition_invoices
         set status = 'paid', paid_amount = amount, renewal = 'continue', paid_at = v_paid_at,
             method = case when h % 4 = 3 then 'cash' else 'transfer' end::public.payment_method
       where id = r.id;
      if h % 4 <> 3 then
        insert into public.bank_transfers (provider, provider_ref, amount, content, received_at, status, invoice_id)
        values ('sepay', 'seed-' || r.id, r.amount, r.payment_code || ' hoc phi thang ' || to_char(r.month, 'MM'),
                v_paid_at, 'matched', r.id)
        on conflict on constraint bank_transfers_once do nothing;
      end if;
    elsif h % 10 = 6 then
      update public.tuition_invoices set renewal = 'continue', due_date = least(v_month + 4, v_today - 1),
             note = 'Hẹn đóng tiền mặt cuối tuần.'
       where id = r.id;
    end if;
  end loop;

  -- 4. Next month's renewal is open, a few have answered.
  perform private.open_month(v_next, v_today);
  for r in
    select i.* from public.tuition_invoices i
     where i.month = v_next and i.status = 'unpaid' and i.paid_amount = 0 and i.student_id is distinct from v_guest
  loop
    h := abs(hashtext(r.payment_code || 'next'));
    if h % 6 = 0 then
      update public.tuition_invoices set status = 'void', void_reason = 'stopped', renewal = 'stop' where id = r.id;
    elsif h % 6 = 1 then
      update public.tuition_invoices
         set status = 'paid', paid_amount = amount, renewal = 'continue', method = 'transfer',
             paid_at = now() - make_interval(hours => 2 + h % 40)
       where id = r.id;
    elsif h % 6 = 2 then
      update public.tuition_invoices set renewal = 'continue' where id = r.id;
    end if;
  end loop;

  -- 5. The inbox: a transfer without a code, and a room deposit set aside.
  insert into public.bank_transfers (provider, provider_ref, amount, content, received_at, status, note) values
    ('sepay', 'seed-unmatched-1', 900000, 'NGUYEN THI HOA chuyen tien hoc nhay', now() - interval '5 hours', 'unmatched',
     'No invoice code in the transfer content.'),
    ('sepay', 'seed-unmatched-2', 1200000, 'MBVCB.8812 hoc phi lop kpop nang cao', now() - interval '1 day', 'unmatched',
     'No invoice code in the transfer content.'),
    ('sepay', 'seed-ignored-1', 250000, 'coc phong A thu 7', now() - interval '3 days', 'ignored', 'Room deposit, not tuition.')
  on conflict on constraint bank_transfers_once do nothing;

  return jsonb_build_object(
    'invoices', (select count(*) from public.tuition_invoices),
    'transfers', (select count(*) from public.bank_transfers));
end;
$$;

