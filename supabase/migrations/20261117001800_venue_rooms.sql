-- Add (p_id null) or change a studio → the studio. p_rooms (when given) is the whole list of its rooms, in
-- order: [{ id?, name, rent, active? }]. Logged in the activity log (area 'rooms').
create function public.venue_save(
  p_id          bigint,
  p_name        text,
  p_address     text default null,
  p_map_url     text default null,
  p_rent        numeric default 0,
  p_note        text default null,
  p_active      boolean default true,
  p_public_name text default null,
  p_rooms       jsonb default null
)
returns public.venues
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v public.venues;
  o public.venues;
  v_name text := btrim(coalesce(p_name, ''));
  v_public text := nullif(btrim(coalesce(p_public_name, '')), '');
  v_map text := nullif(btrim(coalesce(p_map_url, '')), '');
  v_room jsonb;
  v_room_id bigint;
  v_room_name text;
  v_room_rent numeric;
  v_keep bigint[] := '{}';
  v_position int := 0;
  v_rooms_before jsonb;
  v_rooms_after jsonb;
begin
  if not (public.is_staff() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only staff can manage rented studios';
  end if;
  if v_name = '' or char_length(v_name) > 100 then
    raise exception 'INVALID_INPUT: give the studio a name (up to 100 characters)';
  end if;
  if v_public is not null and char_length(v_public) > 80 then
    raise exception 'INVALID_INPUT: the name on the website is up to 80 characters';
  end if;
  if p_rent is null or p_rent < 0 then
    raise exception 'INVALID_INPUT: the rent must be 0 or more';
  end if;
  if v_map is not null and v_map !~ '^https://' then
    raise exception 'INVALID_INPUT: the map link must start with https://';
  end if;
  if exists (select 1 from public.venues x where lower(x.name) = lower(v_name) and x.id is distinct from p_id) then
    raise exception 'INVALID_INPUT: there is already a studio called %', v_name;
  end if;
  if p_rooms is not null then
    if jsonb_typeof(p_rooms) <> 'array' then
      raise exception 'INVALID_INPUT: the rooms are a list';
    end if;
    if exists (select 1 from jsonb_array_elements(p_rooms) e
                group by lower(btrim(coalesce(e ->> 'name', ''))) having count(*) > 1) then
      raise exception 'INVALID_INPUT: two rooms have the same name';
    end if;
  end if;

  if p_id is null then
    insert into public.venues (name, public_name, address, map_url, rent_per_hour, note, active)
    values (v_name, v_public, nullif(left(btrim(coalesce(p_address, '')), 200), ''), v_map, round(p_rent),
            nullif(left(btrim(coalesce(p_note, '')), 300), ''), coalesce(p_active, true))
    returning * into v;
  else
    select * into o from public.venues where id = p_id for update;
    if not found then
      raise exception 'NOT_FOUND: no such studio';
    end if;
    update public.venues
       set name = v_name,
           public_name = v_public,
           address = nullif(left(btrim(coalesce(p_address, '')), 200), ''),
           map_url = v_map,
           rent_per_hour = round(p_rent),
           note = nullif(left(btrim(coalesce(p_note, '')), 300), ''),
           active = coalesce(p_active, true)
     where id = p_id
    returning * into v;
  end if;

  select coalesce(jsonb_agg(jsonb_build_object('name', r.name, 'rent', r.rent_per_hour, 'active', r.active)
                            order by r.position, r.id), '[]'::jsonb)
    into v_rooms_before from public.venue_rooms r where r.venue_id = v.id;

  if p_rooms is not null then
    select coalesce(array_agg(nullif(e ->> 'id', '')::bigint) filter (where nullif(e ->> 'id', '') is not null), '{}')
      into v_keep from jsonb_array_elements(p_rooms) e;
    if exists (select 1 from unnest(v_keep) k where not exists (select 1 from public.venue_rooms r where r.id = k and r.venue_id = v.id)) then
      raise exception 'NOT_FOUND: no such room at this studio';
    end if;

    -- Rooms left out first (so a name can move or come back in the same save): gone, unless a class or a
    -- session was in them (then inactive, keeping their name).
    update public.venue_rooms r set active = false
     where r.venue_id = v.id and not (r.id = any (v_keep))
       and (exists (select 1 from public.classes c where c.venue_room_id = r.id)
            or exists (select 1 from public.instructor_attendance a where a.venue_room_id = r.id));
    delete from public.venue_rooms r
     where r.venue_id = v.id and not (r.id = any (v_keep))
       and not exists (select 1 from public.classes c where c.venue_room_id = r.id)
       and not exists (select 1 from public.instructor_attendance a where a.venue_room_id = r.id);
    if exists (select 1 from jsonb_array_elements(p_rooms) e
                 join public.venue_rooms r on r.venue_id = v.id and not (r.id = any (v_keep))
                where lower(btrim(r.name)) = lower(btrim(coalesce(e ->> 'name', '')))) then
      raise exception 'INVALID_INPUT: a room with that name is kept inactive (classes were in it): use it again or pick another name';
    end if;
    -- Kept rooms step aside for a moment, so names can swap.
    update public.venue_rooms r set name = '~' || r.id where r.id = any (v_keep);

    for v_room in select e from jsonb_array_elements(p_rooms) e loop
      v_room_name := btrim(coalesce(v_room ->> 'name', ''));
      v_room_rent := nullif(v_room ->> 'rent', '')::numeric;
      v_room_id := nullif(v_room ->> 'id', '')::bigint;
      if v_room_name = '' or char_length(v_room_name) > 60 then
        raise exception 'INVALID_INPUT: give each room a name (up to 60 characters)';
      end if;
      if v_room_rent is null or v_room_rent < 0 then
        raise exception 'INVALID_INPUT: a room''s rent must be 0 or more';
      end if;
      if v_room_id is null then
        insert into public.venue_rooms (venue_id, name, rent_per_hour, active, position)
        values (v.id, v_room_name, round(v_room_rent), coalesce((v_room ->> 'active')::boolean, true), v_position);
      else
        update public.venue_rooms
           set name = v_room_name, rent_per_hour = round(v_room_rent),
               active = coalesce((v_room ->> 'active')::boolean, true), position = v_position
         where id = v_room_id and venue_id = v.id;
      end if;
      v_position := v_position + 1;
    end loop;
  end if;

  select coalesce(jsonb_agg(jsonb_build_object('name', r.name, 'rent', r.rent_per_hour, 'active', r.active)
                            order by r.position, r.id), '[]'::jsonb)
    into v_rooms_after from public.venue_rooms r where r.venue_id = v.id;

  insert into public.activity_log (actor_id, actor_name, actor_role, area, action, entity, entity_id, label, changes, meta)
  select auth.uid(), private.person_name(auth.uid()), (select p.role from public.profiles p where p.id = auth.uid()),
         'rooms', case when o.id is null then 'venue_added' else 'venue_changed' end, 'venues', v.id::text, v.name,
         case when o.id is null then null else (
           select nullif(jsonb_object_agg(k, jsonb_build_object('from', to_jsonb(o) -> k, 'to', to_jsonb(v) -> k)), '{}'::jsonb)
             from unnest(array['name', 'public_name', 'address', 'map_url', 'rent_per_hour', 'active']) k
            where to_jsonb(o) -> k is distinct from to_jsonb(v) -> k) end,
         jsonb_build_object('rent', v.rent_per_hour, 'address', v.address, 'active', v.active, 'public_name', v.public_name)
           || case when v_rooms_after is distinct from v_rooms_before
                   then jsonb_build_object('rooms', v_rooms_after, 'rooms_before', v_rooms_before) else '{}'::jsonb end;
  return v;
end;
$$;

revoke execute on function public.venue_save(bigint, text, text, text, numeric, text, boolean, text, jsonb), public.venue_rooms_list()
  from public, anon;
grant execute on function public.venue_save(bigint, text, text, text, numeric, text, boolean, text, jsonb), public.venue_rooms_list()
  to authenticated;

-- One session in another room of its studio (p_room null = no particular room: the studio's own rent). A rent
-- already charged for it follows the new rate (not logged on its own: the session's change is).
create function public.session_set_venue_room(p_session bigint, p_room bigint)
returns public.instructor_attendance
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  a public.instructor_attendance;
  v public.venues;
  r public.venue_rooms;
  w record;
  v_rent numeric;
  v_amount numeric;
  v_logging text := coalesce(current_setting('oops.activity', true), '');
begin
  if not (public.is_staff() or private.is_service_context()) then
    raise exception 'FORBIDDEN: only staff can change a session''s room';
  end if;
  select * into a from public.instructor_attendance where id = p_session for update;
  if not found then
    raise exception 'NOT_FOUND: no such session';
  end if;
  if a.venue_id is null then
    raise exception 'INVALID_STATE: the session isn''t at a rented studio';
  end if;
  if a.status = 'cancelled' then
    raise exception 'INVALID_STATE: the session was called off';
  end if;
  if p_room is not null and not exists (select 1 from public.venue_rooms x where x.id = p_room and x.venue_id = a.venue_id) then
    raise exception 'INVALID_INPUT: that room isn''t at this studio';
  end if;

  update public.instructor_attendance set venue_room_id = p_room where id = a.id returning * into a;

  select * into v from public.venues where id = a.venue_id;
  select * into r from public.venue_rooms where id = a.venue_room_id;
  v_rent := coalesce(r.rent_per_hour, v.rent_per_hour);
  select * into w from private.session_window(a);
  if w.starts_at is not null and w.ends_at is not null then
    v_amount := round(v_rent * extract(epoch from (w.ends_at - w.starts_at)) / 3600 / 1000) * 1000;
  end if;
  if v_amount > 0 then
    perform set_config('oops.activity', 'off', true);
    update public.expenses e
       set amount = v_amount, vendor = left(v.name || coalesce(' · ' || r.name, ''), 120)
     where e.session_id = a.id and e.category = 'venue_rent';
    perform set_config('oops.activity', v_logging, true);
  end if;
  return a;
end;
$$;

revoke execute on function public.session_set_venue_room(bigint, bigint) from public, anon;
grant execute on function public.session_set_venue_room(bigint, bigint) to authenticated;

