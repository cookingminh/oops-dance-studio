-- The room belongs to the studio: picking a room sets the studio; moving to another studio (or a room of
-- the studio's own, or nowhere) drops the old room.
create function private.venue_room_fits()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'UPDATE' and new.venue_id is distinct from old.venue_id
     and new.venue_room_id is not distinct from old.venue_room_id then
    new.venue_room_id := null;
  elsif new.venue_room_id is not null then
    select r.venue_id into new.venue_id from public.venue_rooms r where r.id = new.venue_room_id;
  end if;
  if new.venue_id is null then
    new.venue_room_id := null;
  end if;
  return new;
end;
$$;

